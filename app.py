class HumanBody:
    """
    Five organ models stepped together, each one's output feeding the others.

    The organs are advanced by operator splitting: within one body step the
    coupling variables are held constant, each organ is integrated over that
    step, and the shared variables are then refreshed from the new states. This
    is the standard co-simulation approach and it is accurate as long as the
    body step is short relative to the fastest coupled dynamics, which is why
    `dt` defaults to one minute.
    """

    def __init__(self, parameters=None, surrogate_organs=None, surrogates_root=None):
        """
        `surrogate_organs`: optional subset of ("kidney", "liver", "lungs",
        "pancreas") to advance with their trained BiLSTM surrogates instead
        of the ODE each step -- see the "HYBRID MODE" section of this
        module's docstring. Leave at None (the default) for the original,
        unchanged pure-physics behaviour.
        """
        self.p = copy.deepcopy(parameters if parameters is not None else PARAMETERS)

        self.surrogate_organs = tuple(surrogate_organs) if surrogate_organs else ()
        for organ in self.surrogate_organs:
            if organ not in SURROGATE_ORGANS:
                raise ValueError(
                    "surrogate_organs contains %r, but only %s have a "
                    "coupled-loop surrogate (heart runs on a different "
                    "timescale -- see integration/surrogates.py)."
                    % (organ, SURROGATE_ORGANS))
        # Loaded once here, not in reset(), so repeated resets on one
        # instance don't reload TensorFlow models each time.
        self._surrogates = {
            organ: load_surrogate(organ, surrogates_root)
            for organ in self.surrogate_organs
        }

        self._build_organs()
        self.reset()

    # -- construction ---------------------------------------------------

    def _build_organs(self):
        """Instantiate each organ from its own section of PARAMETERS."""
        ph, pl, pv, pk, pp = (self.p["heart"], self.p["lungs"], self.p["liver"],
                              self.p["kidney"], self.p["pancreas"])

        self.heart = HeartODE(R=ph["R"], C=ph["C"], HR=ph["HR"],
                              EDV=ph["EDV"], ESV=ph["ESV"])

        self.lungs = LungsODE(PiO2=pl["PiO2"], VA=pl["VA"], DL=pl["DL"],
                              VO2=pl["VO2"], VCO2=pl["VCO2"], RQ=pl["RQ"],
                              Vcap=pl["Vcap"],
                              hvr_gain=pl["hvr_gain"],
                              hvr_threshold=pl["hvr_threshold"],
                              hvr_max=pl["hvr_max"],
                              recruit_gain=pl["recruit_gain"],
                              P50=pl["P50"], hill_n=pl["hill_n"])

        self.liver = LiverODE(HGP_max=pv["HGP_max"], HGU_max=pv["HGU_max"],
                              Glyc_max=pv["Glyc_max"], G_thresh=pv["G_thresh"],
                              VO2_base=pv["VO2_base"], alpha=pv["alpha"])

        self.kidney = KidneyODE(RVR=pk["RVR"], FF=pk["FF"], Hct=pk["Hct"],
                                f_reab=pk["f_reab"], Vp_ref=pk["Vp_ref"],
                                U_prod=pk["U_prod"])

        self.pancreas = PancreasODE(Gb=pp["Gb"], Ib=pp["Ib"], p1=pp["p1"],
                                    p2=pp["p2"], p3=pp["p3"], n=pp["n"],
                                    gamma=pp["gamma"], h=pp["h"], V=pp["V"])

    def reset(self):
        """Return every organ to its initial condition."""
        pp, pv, pl, pk, ph = (self.p["pancreas"], self.p["liver"], self.p["lungs"],
                              self.p["kidney"], self.p["heart"])

        self.t = 0.0

        # Pancreas: [G, X, I]
        self.y_pancreas = np.array([pp["G_initial"], pp["X_initial"], pp["I_initial"]],
                                   dtype=float)

        # Liver: [glycogen mass]
        self.y_liver = np.array([pv["Glyc_max"] * pv["glycogen_fill_initial"]], dtype=float)

        # Lungs: [PaO2, PaCO2]. Started at the resting steady state for the
        # altitude at t = 0, so an altitude run does not open with a settling
        # transient that would be mistaken for the ascent response.
        pio2_0 = (pl["PiO2"] if pl["altitude_target"] == 0.0
                  else float(inspired_PO2(self.altitude(0.0))))
        o2_0, co2_0 = self.lungs.resting_steady_state(pio2_0)
        self.y_lungs = np.array([o2_0, co2_0], dtype=float)

        # Kidney: [plasma volume, urea mass]. Urea starts at its own steady
        # state unless the user pinned a BUN, so the record does not open with
        # an artificial transient.
        _, _, gfr0 = self.kidney.renal_flows(ph["MAP_initial"])
        if pk["BUN_initial"] is None:
            Mu0 = pk["U_prod"] * pk["Vp_initial"] / gfr0
        else:
            Mu0 = pk["BUN_initial"] * 10.0 * pk["Vp_initial"]   # mg/dL -> mg/L -> mg
        self.y_kidney = np.array([pk["Vp_initial"], Mu0], dtype=float)

        # Heart is algebraic at this timescale; MAP is carried as shared state.
        self.MAP = ph["MAP_initial"]

        self._history = []
        # Fresh warm-up window per organ on every reset -- a surrogate must
        # not carry history across what is meant to be a new run.
        self._surrogate_history = {
            organ: SurrogateHistory(bundle)
            for organ, (_, bundle) in self._surrogates.items()
        }

    # -- hybrid mode: mapping a step's record onto a surrogate's own -----
    # -- column names -----------------------------------------------------

    def _surrogate_sample(self, organ, record):
        """
        Build the (state + input) sample dict one organ's surrogate expects
        for this step, reading it out of the record just computed for this
        same step -- see `_SURROGATE_FIELD_MAP`'s docstring for why some
        columns are renamed.
        """
        rename = _SURROGATE_FIELD_MAP[organ]
        inverse = {bundle_col: record_field for record_field, bundle_col in rename.items()}
        bundle = self._surrogates[organ][1]
        return {col: record[inverse.get(col, col)] for col in bundle["feature_cols"]}

    # -- protocols ------------------------------------------------------

    def meal_Ra(self, t):
        """Glucose appearance from the gut (mg/min)."""
        pp = self.p["pancreas"]
        return pp["meal_Ra"] if pp["meal_start"] <= t <= pp["meal_end"] else 0.0

    def fluid_intake(self, t):
        """Fluid intake rate (L/min)."""
        pk = self.p["kidney"]
        return (pk["drink_rate"] if pk["drink_start"] <= t <= pk["drink_end"]
                else pk["baseline_intake"])

    def altitude(self, t):
        """
        Altitude (m) at time t: sea level, ascent, hold, descent.

        Returns 0.0 throughout if `altitude_target` is 0, so a sea-level run
        needs no special casing.
        """
        pl = self.p["lungs"]
        target = pl["altitude_target"]
        if target == 0.0:
            return 0.0

        if t < pl["ascent_start"]:
            return 0.0
        if t < pl["ascent_end"]:
            frac = ((t - pl["ascent_start"])
                    / max(1e-9, pl["ascent_end"] - pl["ascent_start"]))
            return target * frac
        if t < pl["descent_start"]:
            return target
        if t < pl["descent_end"]:
            frac = ((t - pl["descent_start"])
                    / max(1e-9, pl["descent_end"] - pl["descent_start"]))
            return target + (pl["altitude_after"] - target) * frac
        return pl["altitude_after"]

    def inspired_O2(self, t):
        """
        Inspired oxygen tension (mmHg) at time t, from the current altitude.

        This is the single channel through which altitude enters the whole body.
        Everything downstream - hypoxaemia, the ventilatory reflex, hypocapnia,
        the fall in contractility, the rise in vascular resistance, the change in
        renal perfusion - follows from it through the ordinary couplings.
        """
        if self.p["lungs"]["altitude_target"] == 0.0:
            return self.p["lungs"]["PiO2"]
        return float(inspired_PO2(self.altitude(t)))

    def exercise_factor(self, t):
        """Metabolic and ventilatory multiplier (dimensionless)."""
        pl = self.p["lungs"]
        return (pl["exercise_factor"]
                if pl["exercise_start"] <= t <= pl["exercise_end"] else 1.0)

    # -- the heart, solved algebraically at the body timescale -----------

    def heart_state(self, PaO2, PaCO2, Vp):
        """
        Compute the heart's output for the current coupled conditions.

        Three couplings enter here.

        Preload (from the kidney): a fuller circulation stretches the ventricle,
        raising end-diastolic volume and therefore stroke volume. This is the
        Frank-Starling mechanism.

        Contractility (from the lungs): low arterial oxygen impairs the
        myocardium and reduces the ejected fraction.

        Resistance (from the lungs): carbon dioxide dilates systemic vessels, so
        a rising PaCO2 lowers vascular resistance.

        Mean arterial pressure then follows exactly from the Windkessel
        relation, mean pressure = resistance x mean flow. No integration is
        needed for the mean, which is what makes the one-minute body step
        possible.
        """
        cp, ph, pk = self.p["coupling"], self.p["heart"], self.p["kidney"]

        # --- preload: kidney -> heart ---------------------------------
        volume_ratio = Vp / pk["Vp_ref"]
        EDV_eff = ph["EDV"] * (1.0 + cp["preload_gain"] * (volume_ratio - 1.0))
        EDV_eff = float(np.clip(EDV_eff, 0.5 * ph["EDV"], 1.6 * ph["EDV"]))

        # --- contractility: lungs -> heart ----------------------------
        hypoxia = max(0.0, cp["hypoxia_ref_PaO2"] - PaO2)
        contractility = float(np.clip(1.0 - cp["hypoxia_sv_gain"] * hypoxia, 0.5, 1.0))

        SV = (EDV_eff - ph["ESV"]) * contractility
        SV = max(SV, 5.0)                       # a ventricle cannot eject nothing

        # --- sympathetic tachycardia: lungs -> heart ------------------
        # Hypoxaemia raises heart rate, which is what actually carries cardiac
        # output up on ascent to altitude.
        deficit = max(0.0, cp["sympathetic_ref_PaO2"] - PaO2) / cp["sympathetic_ref_PaO2"]
        HR_eff = ph["HR"] * (1.0 + cp["sympathetic_hr_gain"] * deficit)
        HR_eff = float(np.clip(HR_eff, ph["HR"], 3.0 * ph["HR"]))

        # --- resistance: lungs -> heart -------------------------------
        co2_excess = PaCO2 - cp["co2_ref_PaCO2"]
        R_eff = ph["R"] * (1.0 - cp["co2_vasodilation_gain"] * co2_excess)
        R_eff = float(np.clip(R_eff, 0.3 * ph["R"], 2.0 * ph["R"]))

        # --- outputs ---------------------------------------------------
        CO = SV * HR_eff / 1000.0               # L/min
        mean_flow = SV * HR_eff / 60.0          # mL/s
        MAP = R_eff * mean_flow                 # mmHg, exact Windkessel mean

        return {
            "MAP_mmHg": MAP,
            "Cardiac_Output_L_min": CO,
            "Stroke_Volume_mL": SV,
            "Heart_Rate_effective_BPM": HR_eff,
            "EDV_effective_mL": EDV_eff,
            "R_effective": R_eff,
            "Contractility": contractility,
        }

    def beat_waveform(self, seconds=5.0, dt=0.01):
        """
        The beat-level pressure waveform at the current coupled state.

        Not part of the coupled loop — the loop uses the mean only — but
        available when the pulsatile detail is wanted, for example to show what
        the one-minute step is averaging over.
        """
        h = self.heart_state(self.y_lungs[0], self.y_lungs[1], self.y_kidney[0])
        beat = HeartODE(R=h["R_effective"], C=self.p["heart"]["C"],
                        HR=self.p["heart"]["HR"],
                        EDV=h["EDV_effective_mL"], ESV=self.p["heart"]["ESV"])
        t_eval = np.arange(0.0, seconds + dt, dt)
        sol = beat.simulate((0.0, seconds), t_eval, [beat.estimate_diastolic_pressure()])
        return pd.DataFrame({"Time_sec": sol.t, "Arterial_Pressure_mmHg": sol.y[0]})

    # -- one coupled step -------------------------------------------------

    def step(self, dt=None):
        """
        Advance the whole body by one step.

        Order of operations: read the couplings, advance every organ over the
        step with those couplings held constant, then refresh the shared
        variables. Every organ therefore sees the same snapshot of the body,
        which keeps the step order from mattering.
        """
        p = self.p
        cp = p["coupling"]
        dt = dt or p["simulation"]["dt"]

        if self.surrogate_organs:
            required_dt = next(iter(self._surrogates.values()))[1]["time_step"]
            if abs(dt - required_dt) > 1e-9:
                raise ValueError(
                    "surrogate_organs requires dt == %.3g minutes (the "
                    "surrogates' own training cadence), got dt=%.3g. Call "
                    "run(dt=%.3g, ...), or set simulation.dt to %.3g in "
                    "PARAMETERS." % (required_dt, dt, required_dt, required_dt))

        t0, t1 = self.t, self.t + dt
        max_step = p["simulation"]["max_step"]
        method = p["simulation"]["solver"]

        # ---- 1. current shared variables ------------------------------
        G = self.y_pancreas[0]          # mg/dL   plasma glucose
        Glyc = self.y_liver[0]          # mg      hepatic glycogen
        PaO2, PaCO2 = self.y_lungs      # mmHg
        Vp, Mu = self.y_kidney          # L, mg

        heart = self.heart_state(PaO2, PaCO2, Vp)
        MAP = heart["MAP_mmHg"]
        CO = heart["Cardiac_Output_L_min"]

        # ---- 2. couplings into each organ -----------------------------

        # pancreas -> liver
        G_to_liver = G * cp["glucose_to_liver_gain"]

        # liver -> pancreas. Net hepatic flux is production minus uptake, so a
        # liver releasing glucose adds to the plasma pool.
        HGP, HGU, Jglyc, hep_VO2 = self.liver.hepatic_fluxes(G_to_liver, Glyc)
        hepatic_Ra = float(HGP - HGU) * cp["hepatic_flux_to_glucose_gain"]

        # liver -> lungs: metabolic work above basal costs oxygen
        extra_VO2 = (float(hep_VO2) - p["liver"]["VO2_base"]) * cp["hepatic_vo2_gain"]

        # heart -> lungs: perfusion-limited exchange
        dl_scale = (CO / cp["co_ref"]) ** cp["perfusion_dl_exponent"]

        # heart -> kidney
        renal_pressure = MAP * cp["map_to_kidney_gain"]

        # ---- 3. advance each organ over [t0, t1] ----------------------
        #
        # An organ named in `self.surrogate_organs` is advanced by its
        # trained BiLSTM surrogate once its warm-up window is full
        # (`_use_surrogate`), and by the physics ODE otherwise -- always
        # true for an organ not requested, and true for the first `window`
        # steps of a hybrid run while history is still filling. Which path
        # ran is recorded in `source` and, when hybrid mode is on, written
        # into this step's record as `<Organ>_Source`.

        def _use_surrogate(organ):
            return (organ in self.surrogate_organs
                    and self._surrogate_history[organ].ready)

        source = {}

        # --- pancreas: gut meal plus hepatic contribution --------------
        total_Ra = self.meal_Ra(t0) + hepatic_Ra
        if _use_surrogate("pancreas"):
            weights, bundle = self._surrogates["pancreas"]
            predicted = predict_next_state(
                weights, bundle, self._surrogate_history["pancreas"].array())
            self.y_pancreas = predicted.astype(float)
            source["pancreas"] = "surrogate"
        else:
            sol = solve_ivp(self.pancreas._bergman_odes, (t0, t1), self.y_pancreas,
                            args=(lambda _t: total_Ra,), method=method, max_step=max_step)
            self.y_pancreas = sol.y[:, -1]
            source["pancreas"] = "physics"

        # --- liver: driven by the pancreas glucose ---------------------
        if _use_surrogate("liver"):
            weights, bundle = self._surrogates["liver"]
            predicted = predict_next_state(
                weights, bundle, self._surrogate_history["liver"].array())
            self.y_liver = predicted.astype(float)
            source["liver"] = "surrogate"
        else:
            sol = solve_ivp(self.liver._hepatic_odes, (t0, t1), self.y_liver,
                            args=(lambda _t: G_to_liver,), method=method, max_step=max_step)
            self.y_liver = sol.y[:, -1]
            source["liver"] = "physics"

        # --- lungs: exercise plus hepatic oxygen demand ----------------
        ex = self.exercise_factor(t0)
        lungs_step = LungsODE(
            PiO2=p["lungs"]["PiO2"], VA=p["lungs"]["VA"],
            DL=p["lungs"]["DL"] * dl_scale,
            VO2=p["lungs"]["VO2"] + max(0.0, extra_VO2),
            VCO2=p["lungs"]["VCO2"], RQ=p["lungs"]["RQ"], Vcap=p["lungs"]["Vcap"],
            hvr_gain=p["lungs"]["hvr_gain"],
            hvr_threshold=p["lungs"]["hvr_threshold"],
            hvr_max=p["lungs"]["hvr_max"],
            recruit_gain=p["lungs"]["recruit_gain"],
            P50=p["lungs"]["P50"], hill_n=p["lungs"]["hill_n"])
        # lungs_step is needed below (hypoxic_drive) regardless of which
        # path advances the state, so it is always built.
        if _use_surrogate("lungs"):
            weights, bundle = self._surrogates["lungs"]
            predicted = predict_next_state(
                weights, bundle, self._surrogate_history["lungs"].array())
            self.y_lungs = predicted.astype(float)
            source["lungs"] = "surrogate"
        else:
            sol = solve_ivp(lungs_step._respiratory_odes, (t0, t1), self.y_lungs,
                            args=(lambda _t: ex, self.inspired_O2),
                            method=method, max_step=max_step)
            self.y_lungs = sol.y[:, -1]
            source["lungs"] = "physics"

        # --- kidney: perfused at the heart's mean pressure -------------
        if _use_surrogate("kidney"):
            weights, bundle = self._surrogates["kidney"]
            predicted = predict_next_state(
                weights, bundle, self._surrogate_history["kidney"].array())
            Vp_new, BUN_new = predicted
            # The surrogate predicts BUN as a concentration (mg/dL),
            # matching what is recorded below; the internal state is urea
            # MASS (mg), matching the physics ODE's own state vector.
            # Convert so both advancement paths leave self.y_kidney in the
            # same representation -- the inverse of the record's own
            # BUN_mg_dL = (Mu / Vp) * 0.1 further down.
            Mu_new = BUN_new * Vp_new * 10.0
            self.y_kidney = np.array([Vp_new, Mu_new], dtype=float)
            source["kidney"] = "surrogate"
        else:
            sol = solve_ivp(self.kidney._guyton_odes, (t0, t1), self.y_kidney,
                            args=(lambda _t: renal_pressure, self.fluid_intake),
                            method=method, max_step=max_step)
            self.y_kidney = sol.y[:, -1]
            source["kidney"] = "physics"

        # ---- 4. record and advance the clock --------------------------
        self.t = t1
        self.MAP = MAP

        _, _, GFR = self.kidney.renal_flows(renal_pressure)
        record = {
            "Time_min": t1,
            # heart
            "MAP_mmHg": MAP,
            "Cardiac_Output_L_min": CO,
            "Stroke_Volume_mL": heart["Stroke_Volume_mL"],
            "Heart_Rate_BPM": heart["Heart_Rate_effective_BPM"],
            "R_effective": heart["R_effective"],
            # lungs
            "PaO2_mmHg": self.y_lungs[0],
            "PaCO2_mmHg": self.y_lungs[1],
            # SaO2 is what a pulse oximeter reads, so it is the one respiratory
            # output that could be checked against a real altitude measurement.
            "SaO2_percent": float(self.lungs.oxygen_saturation(self.y_lungs[0])),
            "Altitude_m": self.altitude(t0),
            "Inspired_O2_mmHg": self.inspired_O2(t0),
            "Alveolar_Ventilation_L_min": (
                p["lungs"]["VA"] * ex
                * float(lungs_step.hypoxic_drive(self.y_lungs[0]))),
            # pancreas
            "Glucose_mg_dL": self.y_pancreas[0],
            "Insulin_Action_1_min": self.y_pancreas[1],
            "Insulin_uU_mL": self.y_pancreas[2],
            # liver
            "Glycogen_Mass_mg": self.y_liver[0],
            "Glycogen_Fill_Fraction": self.y_liver[0] / p["liver"]["Glyc_max"],
            "HGP_mg_min": float(HGP),
            "HGU_mg_min": float(HGU),
            "Hepatic_VO2_mL_min": float(hep_VO2),
            # kidney
            "Plasma_Volume_L": self.y_kidney[0],
            "BUN_mg_dL": (self.y_kidney[1] / self.y_kidney[0]) * 0.1,
            "GFR_L_min": float(GFR),
            "Urine_Output_L_min": float(self.kidney.urine_output(GFR, self.y_kidney[0])),
            # protocols, so a plot can shade the disturbance windows
            "Meal_Ra_mg_min": self.meal_Ra(t0),
            "Fluid_Intake_L_min": self.fluid_intake(t0),
            "Exercise_Factor": ex,
        }

        if self.surrogate_organs:
            # Only present in hybrid runs, so a pure-physics run's output
            # (surrogate_organs=None, the default) has exactly the columns
            # it always had.
            record["Diffusing_Capacity_mL_min_mmHg"] = p["lungs"]["DL"] * dl_scale
            for organ in self.surrogate_organs:
                record["%s_Source" % organ.capitalize()] = source[organ]
                self._surrogate_history[organ].push(self._surrogate_sample(organ, record))

        self._history.append(record)
        return record

    # -- running ----------------------------------------------------------

    def run(self, minutes=None, dt=None, progress_every=None):
        """
        Run the coupled body and return the whole trajectory as a DataFrame.

        One row per body step, with every organ's state in it, so a single frame
        shows how a change in one organ propagated to the others.
        """
        minutes = minutes or self.p["simulation"]["duration"]
        dt = dt or self.p["simulation"]["dt"]
        n_steps = int(round(minutes / dt))

        for i in range(n_steps):
            self.step(dt)
            if progress_every and (i + 1) % progress_every == 0:
                print("  t = %6.0f min   MAP %.1f mmHg   glucose %.1f mg/dL"
                      % (self.t, self.MAP, self.y_pancreas[0]))

        return pd.DataFrame(self._history)

    # -- checks -----------------------------------------------------------

    def steady_state_check(self, minutes=240.0, tolerance=None):
        """
        Run with every disturbance switched off and confirm nothing drifts.

        This is the first test any coupled model has to pass. Feedback loops can
        accumulate small errors until the whole system leaves physiological
        range, even when every component is individually accurate, and a body
        that cannot sit still cannot be trusted to respond correctly to
        anything.

        Returns a dict of the drift in each variable over the run.
        """
        quiet = copy.deepcopy(self.p)
        quiet["pancreas"]["meal_Ra"] = 0.0
        quiet["lungs"]["exercise_factor"] = 1.0
        quiet["kidney"]["drink_rate"] = quiet["kidney"]["baseline_intake"]
        quiet["lungs"]["altitude_target"] = 0.0

        body = HumanBody(quiet)
        df = body.run(minutes=minutes)

        watch = ["MAP_mmHg", "PaO2_mmHg", "PaCO2_mmHg", "SaO2_percent",
                 "Glucose_mg_dL", "Plasma_Volume_L", "BUN_mg_dL",
                 "Glycogen_Fill_Fraction"]

        tolerance = tolerance or {
            "MAP_mmHg": 5.0, "PaO2_mmHg": 5.0, "PaCO2_mmHg": 3.0,
            "SaO2_percent": 2.0,
            "Glucose_mg_dL": 10.0, "Plasma_Volume_L": 0.15,
            "BUN_mg_dL": 2.0, "Glycogen_Fill_Fraction": 0.15,
        }

        out = {}
        for col in watch:
            drift = float(df[col].iloc[-1] - df[col].iloc[0])
            out[col] = {
                "start": float(df[col].iloc[0]),
                "end": float(df[col].iloc[-1]),
                "drift": drift,
                "tolerance": tolerance[col],
                "stable": abs(drift) <= tolerance[col],
            }
        return out, df


