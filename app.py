# ===========================================================================
#   PHARMACOKINETICS
#   A one-compartment, first-order absorption/elimination curve, normalised
#   to its own peak so it can be used directly as a 0..1 fraction of a
#   drug's peak physiological effect -- the same role `hypoxic_drive` plays
#   for altitude in the lungs model.
# ===========================================================================

def peak_time(ka, ke):
    """Minutes from administration to peak concentration, for first-order
    absorption rate `ka` and elimination rate `ke` (both 1/min)."""
    if abs(ka - ke) < 1e-9:
        return 1.0 / ke
    return float(np.log(ka / ke) / (ka - ke))


def concentration_fraction(t, t_admin, ka, ke):
    """
    Normalised (0..1) plasma-concentration-shaped time course for a single
    dose: zero before `t_admin`, rising as the drug is absorbed, peaking at
    exactly 1.0 at `t_admin + peak_time(ka, ke)`, then decaying as it's
    eliminated. `ka` is the absorption rate constant, `ke` the elimination
    rate constant (both 1/min) -- `ke = ln(2) / elimination_half_life_min`.
    """
    if t <= t_admin or ka <= 0 or ke <= 0:
        return 0.0
    dt = t - t_admin
    tp = peak_time(ka, ke)
    if abs(ka - ke) < 1e-9:
        raw = ke * dt * np.exp(-ke * dt)
        peak = ke * tp * np.exp(-ke * tp)
    else:
        raw = np.exp(-ke * dt) - np.exp(-ka * dt)
        peak = np.exp(-ke * tp) - np.exp(-ka * tp)
    if peak <= 0:
        return 0.0
    return float(np.clip(raw / peak, 0.0, 1.0))


# ===========================================================================
#   DOSE SCALING
# ===========================================================================

_MAX_EFFECT_MAGNITUDE = 0.60   # a dose can never push a target parameter's
                               # fractional change beyond +-60% of baseline,
                               # regardless of how high the slider is set.


def effective_peak_delta_frac(target, drug, dose_mg):
    """The fractional change actually applied to one target at `dose_mg`,
    linearly scaled from the drug's documented reference dose, then
    clamped to +-60% so no slider position can drive a target parameter
    non-physical."""
    scale = float(dose_mg) / drug["standard_dose_mg"]
    eff = target["peak_delta_frac"] * scale
    return float(np.clip(eff, -_MAX_EFFECT_MAGNITUDE, _MAX_EFFECT_MAGNITUDE))


