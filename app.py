def _minutes_to_hm(total_minutes):
    return divmod(int(round(total_minutes)), 60)


def _render_time_control(section, name, meta, container):
    """Elapsed-hours-and-minutes variant of render_param_control, used only
    for the ten parameters in _TIME_PARAM_NAMES. Same reset-button contract
    and the same pending-reset queue as the plain slider path below (see
    render_param_control's docstring for why resets have to be queued
    rather than applied immediately) -- it just seeds two widget keys
    (hours, minutes) instead of one.
    """
    ctrl_key = "ctrl_%s_%s" % (section, name)
    hr_key = ctrl_key + "_hr"
    min_key = ctrl_key + "_min"
    reset_key = "reset_%s_%s" % (section, name)
    default_val = BASE_PARAMS[section][name]

    if (section, name) in st.session_state._pending_resets:
        st.session_state._pending_resets.discard((section, name))
        d_hr, d_min = _minutes_to_hm(default_val)
        st.session_state[hr_key] = d_hr
        st.session_state[min_key] = d_min
        st.session_state.params[section][name] = default_val

    current = float(np.clip(st.session_state.params[section][name], meta["min"], meta["max"]))
    init_hr, init_min = _minutes_to_hm(current)
    max_hr = int(meta["max"]) // 60
    minute_step = int(meta["step"]) if meta["step"] < 60 else 5

    container.caption("%s -- elapsed since run start" % name, help=meta["help"])
    hr_col, min_col, reset_col = container.columns([2, 2, 1])
    hr = hr_col.number_input(
        "h", min_value=0, max_value=max_hr, value=init_hr, step=1,
        key=hr_key, help=meta["help"],
    )
    mn = min_col.number_input(
        "min", min_value=0, max_value=59, value=init_min, step=minute_step,
        key=min_key, help=meta["help"],
    )
    total = float(np.clip(hr * 60 + mn, meta["min"], meta["max"]))
    st.session_state.params[section][name] = total
    is_default = abs(total - float(default_val)) < 1e-9
    reset_col.write("")   # vertical spacer so the button lines up with the number inputs
    d_hr, d_min = _minutes_to_hm(default_val)
    if reset_col.button(
        "↺", key=reset_key, disabled=is_default,
        help=("Already at its default" if is_default else "Reset to default (%dh %02dm)" % (d_hr, d_min)),
    ):
        st.session_state._pending_resets.add((section, name))
        st.rerun()


