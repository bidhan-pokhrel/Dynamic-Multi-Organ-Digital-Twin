_SURROGATES_DIR = os.path.dirname(os.path.abspath(__file__))


def _bundle_path(organ, root):
    return os.path.join(root, "%s_surrogate.pkl" % organ)


# Cache by (organ, models_root): rebuilding a BiLSTM's architecture and
# loading its weights off disk is not free, and a caller that builds many
# short-lived HumanBody(surrogate_organs=...) instances in a loop (a
# parameter sweep or coupling ablation in this app) would otherwise pay
# that cost again for every single one. See the original
# integration/surrogates.py docstring for the full reasoning (identical
# here, only the on-disk format changed).
_SURROGATE_CACHE = {}


def load_surrogate(organ, models_root=None):
    """
    Load one organ's trained surrogate from its consolidated
    <organ>_surrogate.pkl -- a pickle of {"bundle": {...same fields as the
    original <organ>_bundle_portable.json, with x_mean/x_std/y_mean/y_std
    as numpy arrays...}, "weights": [...the trained Keras weights, from
    model.get_weights()...]}, produced once for this flat deployment
    bundle so no numpy-version-dependent .pkl unpickle and no JSON+H5
    sidecar pair are needed at runtime.

    Returns (model, bundle): a compiled-for-inference Keras model with the
    trained weights loaded, and a bundle dict -- the same shape the
    original loaders return, so this is interchangeable with them at the
    call site.

    `models_root` defaults to this file's own directory (the flat
    deployment bundle keeps every <organ>_surrogate.pkl next to app.py
    itself, not under a bilstm_models/<organ>/ subfolder).

    Cached per (organ, models_root) for the lifetime of the process.
    """
    models_root = models_root or _SURROGATES_DIR
    if organ not in SURROGATE_ORGANS:
        raise ValueError(
            "No coupled-loop surrogate available for organ %r. Available: "
            "%s (heart is excluded -- see this section's docstring)."
            % (organ, SURROGATE_ORGANS))

    cache_key = (organ, models_root)
    if cache_key in _SURROGATE_CACHE:
        return _SURROGATE_CACHE[cache_key]

    with open(_bundle_path(organ, models_root), "rb") as f:
        payload = pickle.load(f)
    bundle = payload["bundle"]
    weights = payload["weights"]   # the 10-array list from Keras's model.get_weights()

    _SURROGATE_CACHE[cache_key] = (weights, bundle)
    return weights, bundle

def predict_next_state(weights, bundle, window_array):
    """
    Advance one organ by a single surrogate step, using the pure-NumPy
    Bidirectional-LSTM forward pass above (see its own docstring for the
    architecture and the numerical verification against the original
    TensorFlow/Keras model this replaces).

    Parameters
    ----------
    weights : list of ndarray
        The trained Keras weights for this organ, from load_surrogate.
    window_array : ndarray, shape (window, n_features)
        The most recent `window` samples of state+input variables, in the
        column order `bundle["feature_cols"]`, in physical units.

    Returns
    -------
    ndarray, shape (n_state,)
        The predicted state at the next step, in physical units.
    """
    x_mean = np.asarray(bundle["x_mean"]).reshape(-1)
    x_std = np.asarray(bundle["x_std"]).reshape(-1)
    y_mean = np.asarray(bundle["y_mean"]).reshape(-1)
    y_std = np.asarray(bundle["y_std"]).reshape(-1)

    window_scaled = (window_array - x_mean) / x_std
    delta_scaled = _bilstm_forward(weights, window_scaled)
    delta = delta_scaled * y_std + y_mean

    n_state = len(bundle["state_cols"])
    last_state = window_array[-1, :n_state]
    return (last_state + delta).astype("float64")


class SurrogateHistory:
    """
    A rolling window of one organ's own (state + input) samples, in the
    exact column order and cadence its surrogate was trained on, so
    `predict_next_state` always gets a well-formed window once warm-up is
    complete.

    Warm-up: `ready` is False until `window` samples have been pushed, one
    per body step. In HumanBody, the organ is advanced by physics during
    warm-up (there is no alternative -- the surrogate cannot predict from
    a window it hasn't got yet) and by the surrogate once `ready` is True.
    """

    def __init__(self, bundle):
        self.bundle = bundle
        self.window = bundle["window"]
        self.columns = bundle["feature_cols"]
        self._rows = []

    def push(self, sample):
        """`sample`: dict containing at least every column in self.columns."""
        self._rows.append([float(sample[c]) for c in self.columns])
        if len(self._rows) > self.window:
            self._rows.pop(0)

    @property
    def ready(self):
        return len(self._rows) >= self.window

    def array(self):
        return np.array(self._rows[-self.window:], dtype="float32")


