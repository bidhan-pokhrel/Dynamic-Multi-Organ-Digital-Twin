#   THE INTERVENTION MODEL
#   A subclass, not an edit -- human_body.py is untouched.
# ===========================================================================

def _holder_for(body, organ):
    """
    The object whose attribute a drug targeting `organ` should mutate.

    heart_state() re-reads self.p["heart"] fresh every step, and the lungs
    organ is rebuilt from self.p["lungs"] fresh every step (see step() in
    human_body.py) -- so for those two organs, the PARAMETERS dict section
    IS live. Kidney, pancreas and liver are persistent ODE objects built
    once in _build_organs() whose own methods read `self.<attr>` off that
    object, so a drug targeting one of those has to mutate the organ
    instance itself for the change to reach the ODE.
    """
    if organ in ("heart", "lungs"):
        return body.p[organ]
    return getattr(body, organ)


def _get_value(holder, attr):
    if isinstance(holder, dict):
        return holder[attr]
    return getattr(holder, attr)


def _set_value(holder, attr, value):
    if isinstance(holder, dict):
        holder[attr] = value
    else:
        setattr(holder, attr, value)


class HumanBodyWithInterventions(HumanBody):
    """
    HumanBody, plus zero or more drugs administered during the run.

    Every organ, every ODE, every coupling is inherited unchanged --
    step() only adds "compute this step's dose fraction for each active
    drug, and set every one of its target parameters accordingly"
    immediately before calling the real HumanBody.step(). Nothing here
    duplicates or re-derives any physiology; it only ever nudges parameters
    the organs already have.
    """

    def __init__(self, parameters=None, drugs=None):
        """
        `drugs`: a list of {"drug": DRUGS[name], "dose_mg": float} dicts.
        Supports more than one drug at once (polypharmacy) since each
        entry is independent -- untested combination effects are exactly
        what a coupled model is for.
        """
        super().__init__(parameters)
        self.drugs = list(drugs or [])
        self._baseline = {}   # keyed by (drug label, organ, attr)
        for entry in self.drugs:
            drug = entry["drug"]
            for target in drug["targets"]:
                holder = _holder_for(self, target["organ"])
                key = (drug["label"], target["organ"], target["attr"])
                self._baseline[key] = _get_value(holder, target["attr"])

    def step(self, dt=None):
        t0 = self.t
        dose_fractions = {}
        for entry in self.drugs:
            drug, dose_mg = entry["drug"], entry["dose_mg"]
            frac = concentration_fraction(t0, drug["t_admin"], drug["ka"], drug["ke"])
            dose_fractions[drug["label"]] = frac
            for target in drug["targets"]:
                holder = _holder_for(self, target["organ"])
                key = (drug["label"], target["organ"], target["attr"])
                baseline_val = self._baseline[key]
                eff = effective_peak_delta_frac(target, drug, dose_mg)
                new_val = baseline_val * (1.0 + eff * frac)
                _set_value(holder, target["attr"], new_val)

        record = super().step(dt)

        for label, frac in dose_fractions.items():
            record["Dose_%s" % label] = frac
        return record


