def run_scenario(name, minutes=1440.0, base_params=None):
    """
    Run one named scenario against a healthy baseline, both with the same
    meal/drink/exercise protocol active. Returns (baseline_df, scenario_df).

    `base_params` lets a caller (e.g. the Streamlit app) apply the disease
    overrides on top of a customised parameter set instead of the pure
    defaults -- so "run this disease scenario" and "the sliders I've
    already tuned" compose instead of one silently overriding the other.
    Defaults to `PARAMETERS` (the same behaviour as before this parameter
    existed).
    """
    if name not in SCENARIOS:
        raise KeyError("No such scenario %r. Known scenarios: %s" % (name, list(SCENARIOS)))

    base = copy.deepcopy(base_params if base_params is not None else PARAMETERS)

    baseline_df = HumanBody(copy.deepcopy(base)).run(minutes=minutes)
    scenario_df = run_with(SCENARIOS[name]["overrides"], minutes=minutes, base=base)
    return baseline_df, scenario_df


def evaluate_effects(baseline_df, scenario_df, expect):
    """
    Compare a baseline run and a scenario run against a list of expected
    effects -- (column, "up"/"down"/"flat", rationale) tuples, the same
    shape as SCENARIOS[name]["expect"]. Returns a DataFrame: one row per
    expected effect, with the actual end-of-run values, the direction
    predicted, and whether it held.

    Factored out from evaluate_scenario() so it can be reused against any
    pair of runs -- not just a scenario vs. the pure defaults -- for
    example the Streamlit app evaluating a scenario against whatever the
    sidebar currently holds.
    """
    rows = []
    for col, direction, rationale in expect:
        base_end = float(baseline_df[col].iloc[-1])
        scen_end = float(scenario_df[col].iloc[-1])
        delta = scen_end - base_end

        if direction == "up":
            holds = delta > 0
        elif direction == "down":
            holds = delta < 0
        else:  # "flat"
            # "Flat" is judged relative to the variable's own scale, not
            # an absolute number -- 1% of the baseline value.
            holds = abs(delta) < max(abs(base_end) * 0.01, 1e-6)

        rows.append({
            "variable": col,
            "expected": direction,
            "baseline_end": round(base_end, 4),
            "scenario_end": round(scen_end, 4),
            "delta": round(delta, 4),
            "holds": holds,
            "rationale": rationale,
        })

    return pd.DataFrame(rows)


def evaluate_scenario(name, minutes=1440.0, base_params=None):
    """
    Run a scenario and check its expected effects, the same directional
    style as evaluate_system.ipynb's Section 5. Returns a DataFrame in the
    shape evaluate_effects() produces.
    """
    baseline_df, scenario_df = run_scenario(name, minutes=minutes, base_params=base_params)
    return evaluate_effects(baseline_df, scenario_df, SCENARIOS[name]["expect"])


def evaluate_all_scenarios(minutes=1440.0):
    """Run and evaluate every scenario. Returns {name: evaluation_df}."""
    return {name: evaluate_scenario(name, minutes=minutes) for name in SCENARIOS}



# ORGAN_SIGNATURE_COLUMNS and _NO_EFFECT_THRESHOLD: identical to drug_interventions.py's copies
# below (verified byte-for-byte identical before collapsing -- see the assembly report) --
# defined once there instead of duplicated here, matching this flat file's single namespace.

def disease_organ_impact_summary(name, baseline_df, scenario_df):
    """
    For every one of the five organs, classify how scenario `name` affected
    it by run end (the same end-of-run convention evaluate_effects() uses),
    using whichever baseline_df/scenario_df pair the caller ran -- this
    function only reads the resulting state, never which engine (pure
    physics or a BiLSTM surrogate) produced it. Disease scenarios always run
    pure physics in this app regardless of that choice (see this module's
    docstring and app.py's own caption for why), but the function itself
    stays engine-agnostic.

    Three verdicts, deliberately different from drug_interventions.py's
    four -- a disease preset has no "desired" vs. "side effect" framing the
    way a drug's expect list does, so "did the coupling carry this to
    another organ" is the only question worth asking here:

      "Directly affected"         -- this organ's own ODE parameters were
                                      changed by the scenario's overrides
                                      (SCENARIOS[name]["overrides"]). Shown
                                      regardless of how large the resulting
                                      change in its signature columns turns
                                      out to be -- it's a statement about
                                      the mechanism, not the magnitude (see
                                      CIRRHOSIS's HGU_mg_min for a
                                      directly-overridden organ whose own
                                      signature barely moves, because the
                                      liver's glucose-uptake switch never
                                      activates on a healthy baseline).
      "Downstream effect"         -- a *different* organ's parameters were
                                      changed, but this organ's own
                                      signature columns still moved by more
                                      than the 2% floor at run end -- a
                                      genuine cross-organ coupling effect,
                                      exactly what the coupled model exists
                                      to demonstrate.
      "Not meaningfully affected" -- nothing in this organ's signature
                                      columns moved by more than 2% at run
                                      end, and this organ's own parameters
                                      were not part of the scenario.

    Returns {organ: {"verdict": ..., "max_abs_pct_change": ...,
                      "column_pct_changes": {col: signed_pct_change, ...}}}.
    """
    if name not in SCENARIOS:
        raise KeyError("No such scenario %r. Known scenarios: %s" % (name, list(SCENARIOS)))

    overridden_organs = set(SCENARIOS[name]["overrides"].keys())

    summary = {}
    for organ, cols in ORGAN_SIGNATURE_COLUMNS.items():
        pct_by_col = {}
        for c in cols:
            b = float(baseline_df[c].iloc[-1])
            s = float(scenario_df[c].iloc[-1])
            pct_by_col[c] = (s - b) / max(abs(b), 1e-6)
        max_abs_pct = max(abs(p) for p in pct_by_col.values())

        if organ in overridden_organs:
            verdict = "Directly affected"
        elif max_abs_pct >= _NO_EFFECT_THRESHOLD:
            verdict = "Downstream effect"
        else:
            verdict = "Not meaningfully affected"

        summary[organ] = {
            "verdict": verdict,
            "max_abs_pct_change": round(max_abs_pct * 100.0, 2),
            "column_pct_changes": {c: round(p * 100.0, 2) for c, p in pct_by_col.items()},
        }
    return summary


