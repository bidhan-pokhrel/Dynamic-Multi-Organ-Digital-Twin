def _scenario_base(scenario_name):
    """A PARAMETERS dict with a disease scenario's overrides already
    applied, for testing a drug against a diseased baseline instead of the
    healthy defaults -- e.g. furosemide against CKD."""
    if scenario_name is None:
        return copy.deepcopy(PARAMETERS)
    if scenario_name not in SCENARIOS:
        raise KeyError("No such scenario %r. Known scenarios: %s" % (scenario_name, list(SCENARIOS)))
    base = copy.deepcopy(PARAMETERS)
    for organ, changes in SCENARIOS[scenario_name]["overrides"].items():
        base[organ].update(changes)
    return base


def run_intervention(name, minutes=1440.0, base_params=None, scenario=None, dose_mg=None):
    """
    Run one named drug, at `dose_mg` (defaults to its documented standard
    dose), against a baseline with no drug, both on the same underlying
    parameters. Returns (baseline_df, treated_df).

    `base_params` lets a caller (e.g. the Streamlit app) supply an already-
    customised parameter set as the common starting point for both runs.
    `scenario` is a convenience for testing a drug against one of
    SCENARIOS's disease presets by name (e.g. scenario="CKD") instead of
    the healthy defaults; ignored if `base_params` is given explicitly.
    """
    if name not in DRUGS:
        raise KeyError("No such drug %r. Known drugs: %s" % (name, list(DRUGS)))
    drug = DRUGS[name]
    dose_mg = drug["standard_dose_mg"] if dose_mg is None else dose_mg

    base = copy.deepcopy(base_params) if base_params is not None else _scenario_base(scenario)

    baseline_df = HumanBody(copy.deepcopy(base)).run(minutes=minutes)
    treated_df = HumanBodyWithInterventions(
        copy.deepcopy(base), drugs=[{"drug": drug, "dose_mg": dose_mg}],
    ).run(minutes=minutes)
    return baseline_df, treated_df


def evaluate_intervention(baseline_df, treated_df, expect, eval_time):
    """
    Compare a baseline run and a treated run at a specific point in time --
    the time of peak drug concentration, not the end of the run, since a
    drug's effect is transient by design. `expect` is a list of dicts
    (see DRUGS above): {"column", "organ", "direction", "desired",
    "rationale"}.
    """
    idx_b = int((baseline_df["Time_min"] - eval_time).abs().idxmin())
    idx_t = int((treated_df["Time_min"] - eval_time).abs().idxmin())

    rows = []
    for e in expect:
        col, direction = e["column"], e["direction"]
        base_val = float(baseline_df[col].iloc[idx_b])
        treat_val = float(treated_df[col].iloc[idx_t])
        delta = treat_val - base_val

        if direction == "up":
            holds = delta > 0
        elif direction == "down":
            holds = delta < 0
        else:  # "flat"
            holds = abs(delta) < max(abs(base_val) * 0.05, 1e-6)

        rows.append({
            "variable": col,
            "organ": e["organ"],
            "desired": e["desired"],
            "expected": direction,
            "eval_time_min": round(float(baseline_df["Time_min"].iloc[idx_b]), 1),
            "baseline_value": round(base_val, 4),
            "treated_value": round(treat_val, 4),
            "delta": round(delta, 4),
            "holds": holds,
            "rationale": e["rationale"],
        })

    return pd.DataFrame(rows)


def evaluate_drug(name, minutes=1440.0, base_params=None, scenario=None, dose_mg=None):
    """Run a drug and check its expected effects at its own peak-effect
    time. Returns (baseline_df, treated_df, evaluation_df)."""
    drug = DRUGS[name]
    baseline_df, treated_df = run_intervention(
        name, minutes=minutes, base_params=base_params, scenario=scenario, dose_mg=dose_mg,
    )
    eval_time = drug["t_admin"] + peak_time(drug["ka"], drug["ke"])
    result = evaluate_intervention(baseline_df, treated_df, drug["expect"], eval_time)
    return baseline_df, treated_df, result


def evaluate_all_drugs(minutes=1440.0):
    """Run and evaluate every drug against its suggested baseline. Returns
    {name: (baseline_df, treated_df, evaluation_df)}."""
    return {
        name: evaluate_drug(name, minutes=minutes, scenario=DRUGS[name]["suggested_scenario"])
        for name in DRUGS
    }


# ===========================================================================
#   POLYPHARMACY (multiple drugs at once)
#   HumanBodyWithInterventions.drugs already accepts a list -- see its own
#   docstring ("Supports more than one drug at once ... untested combination
#   effects are exactly what a coupled model is for"). run_intervention()
#   above only ever builds a one-drug list from that support; this section
#   is the many-drug entry point the class was already built for, exposed
#   as its own function rather than overloading run_intervention()'s single
#   `name` argument into also accepting a list.
# ===========================================================================

def run_multi_intervention(drug_doses, minutes=1440.0, base_params=None, scenario=None):
    """
    Run several drugs at once (polypharmacy) against one shared baseline
    with no drugs at all. `drug_doses` is a list of (drug_name, dose_mg)
    tuples -- dose_mg may be None to use that drug's own documented
    standard dose. Returns (baseline_df, treated_df).

    Every entry acts through HumanBodyWithInterventions.step() completely
    independently of every other (see that class's docstring) -- this
    function does not add any drug-drug interaction model of its own; any
    combined effect visible in the output is whatever the shared organ
    ODEs and coupling graph produce from each drug's own parameter nudge
    landing on the same body at the same time, not a modelled interaction.
    """
    base = copy.deepcopy(base_params) if base_params is not None else _scenario_base(scenario)

    drugs = []
    for name, dose_mg in drug_doses:
        if name not in DRUGS:
            raise KeyError("No such drug %r. Known drugs: %s" % (name, list(DRUGS)))
        drug = DRUGS[name]
        dose = drug["standard_dose_mg"] if dose_mg is None else dose_mg
        drugs.append({"drug": drug, "dose_mg": dose})

    baseline_df = HumanBody(copy.deepcopy(base)).run(minutes=minutes)
    treated_df = HumanBodyWithInterventions(copy.deepcopy(base), drugs=drugs).run(minutes=minutes)
    return baseline_df, treated_df


def organ_impact_summary_multidrug(drug_names, baseline_df, treated_df):
    """
    Cross-organ verdict for a polypharmacy run -- the multi-drug
    counterpart to organ_impact_summary() above, needed because that
    function's four-way Positive/Negative/Balanced/No-effect scheme reads
    one drug's own `expect` list at one drug's own peak-concentration
    time, neither of which is well-defined for an arbitrary combination of
    drugs that each peak at a different time with no single shared
    "intended effect" to check the mix against.

    Two differences from the single-drug version:
      - Uses the PEAK absolute deviation over the WHOLE run, at whichever
        timestep produces it, rather than one fixed eval_time snapshot --
        because different drugs in the mix peak at different times, there
        is no one instant that fairly represents "the effect" the way a
        single drug's own peak time does.
      - Three-way verdict, same style as disease_scenarios.py's
        organ_impact_summary(), since a drug combination has no single
        "desired" framing to judge against either:

          "Directly affected"         -- at least one selected drug has a
                                          target on this organ's own
                                          parameters (drug["targets"]).
          "Downstream effect"         -- no selected drug targets this
                                          organ directly, but its signature
                                          columns still moved by more than
                                          the 2% floor somewhere in the run
                                          -- a genuine cross-organ coupling
                                          effect from a drug targeting a
                                          *different* organ.
          "Not meaningfully affected" -- neither of the above.

    Returns {organ: {"verdict", "max_abs_pct_change", "peak_time_min",
                      "column_pct_changes": {col: signed_pct_at_peak}}}.
    """
    targeted_organs = set()
    for name in drug_names:
        for target in DRUGS[name]["targets"]:
            targeted_organs.add(target["organ"])

    n = min(len(baseline_df), len(treated_df))
    b, t = baseline_df.iloc[:n], treated_df.iloc[:n]
    times = b["Time_min"].values

    summary = {}
    for organ, cols in ORGAN_SIGNATURE_COLUMNS.items():
        b_mat = b[cols].to_numpy(dtype=float)
        t_mat = t[cols].to_numpy(dtype=float)
        pct = (t_mat - b_mat) / np.maximum(np.abs(b_mat), 1e-6)   # (n, k)
        abs_row_max = np.abs(pct).max(axis=1)                      # (n,)
        peak_i = int(np.argmax(abs_row_max))
        max_abs_pct = float(abs_row_max[peak_i])

        if organ in targeted_organs:
            verdict = "Directly affected"
        elif max_abs_pct >= _NO_EFFECT_THRESHOLD:
            verdict = "Downstream effect"
        else:
            verdict = "Not meaningfully affected"

        summary[organ] = {
            "verdict": verdict,
            "max_abs_pct_change": round(max_abs_pct * 100.0, 2),
            "peak_time_min": round(float(times[peak_i]), 1),
            "column_pct_changes": {
                c: round(float(pct[peak_i, j]) * 100.0, 2) for j, c in enumerate(cols)
            },
        }
    return summary


# ===========================================================================
#   "AI's point of view" -- a plain-language, per-organ verdict
#   Deterministic and rule-based (not a model call): built directly from
#   the same evaluate_intervention() output already computed above, so a
#   non-specialist reading the app doesn't have to interpret a numeric
#   table to see what a drug did to an organ it didn't obviously target.
# ===========================================================================

def organ_impact_summary(drug, baseline_df, treated_df, evaluation_df, eval_time):
    """
    For every one of the five organs, decide one of four verdicts:

      "Positive"  -- the drug's intended (desired=True) effect on this
                     organ held, and nothing else meaningful went wrong.
      "Negative"  -- an unwanted (desired=False) side effect held on this
                     organ, or the drug's intended effect here did not
                     hold despite a meaningful change happening.
      "Balanced"  -- a mix of intended and side effects held together, or
                     a meaningful change happened with no explicit
                     expectation attached to interpret it (a real,
                     unlabelled co-related-organ effect).
      "No effect" -- nothing on this organ moved by more than 2%,
                     regardless of what any expect entry claims -- this is
                     checked FIRST, so a drug deliberately tuned to be
                     negligible at a normal dose (paracetamol) reads "No
                     effect" there rather than "Negative" from a
                     technically-correct but trivial direction match.

    Returns {organ: {"verdict": ..., "max_abs_pct_change": ...}}.
    """
    idx_b = int((baseline_df["Time_min"] - eval_time).abs().idxmin())
    idx_t = int((treated_df["Time_min"] - eval_time).abs().idxmin())

    summary = {}
    for organ, cols in ORGAN_SIGNATURE_COLUMNS.items():
        pct_changes = []
        for c in cols:
            b = float(baseline_df[c].iloc[idx_b])
            t = float(treated_df[c].iloc[idx_t])
            pct_changes.append((t - b) / max(abs(b), 1e-6))
        max_abs_pct = max(abs(p) for p in pct_changes)

        rows = evaluation_df[evaluation_df["organ"] == organ] if not evaluation_df.empty else evaluation_df
        desired_rows = rows[rows["desired"]] if len(rows) else rows
        side_effect_rows = rows[~rows["desired"]] if len(rows) else rows

        good = desired_rows[desired_rows["holds"]] if len(desired_rows) else desired_rows
        missed = desired_rows[~desired_rows["holds"]] if len(desired_rows) else desired_rows
        bad = side_effect_rows[side_effect_rows["holds"]] if len(side_effect_rows) else side_effect_rows

        n_good, n_missed, n_bad = len(good), len(missed), len(bad)

        if max_abs_pct < _NO_EFFECT_THRESHOLD:
            # Nothing moved meaningfully -- true regardless of what any
            # expect entry's pure direction check says, so a drug tuned to
            # be negligible at this dose reads "No effect", not "Negative"
            # from a trivial sign match.
            verdict = "No effect"
        elif n_bad > 0 and n_good == 0:
            verdict = "Negative"
        elif n_bad > 0 and n_good > 0:
            verdict = "Balanced"
        elif n_good > 0 and n_missed == 0 and n_bad == 0:
            verdict = "Positive"
        elif n_missed > 0 and n_good == 0 and n_bad == 0:
            # A meaningful change happened, but not in the intended
            # direction -- the treatment backfired on this organ.
            verdict = "Negative"
        elif n_good == 0 and n_missed == 0 and n_bad == 0:
            # A meaningful change happened with no expect entry to
            # interpret it -- a real, unlabelled co-related-organ effect.
            verdict = "Balanced"
        else:
            verdict = "Balanced"

        summary[organ] = {
            "verdict": verdict,
            "max_abs_pct_change": round(max_abs_pct * 100.0, 2),
        }
    return summary



