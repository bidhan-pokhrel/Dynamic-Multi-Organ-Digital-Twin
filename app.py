# ===========================================================================
#   Heart -- already fully self-contained (Windkessel model needs nothing
#   from another organ), same as `HeartODE.generate_synthetic_cohort` and
#   `human_body.py`'s own `beat_waveform()`.
# ===========================================================================

def run_heart(constructor_params, seconds=10.0, dt_sec=0.01):
    heart = HeartODE(**constructor_params)
    y0 = [heart.estimate_diastolic_pressure()]
    t_eval = np.arange(0.0, seconds + dt_sec, dt_sec)
    sol = heart.simulate((0.0, seconds), t_eval, y0)

    Q_flow = np.array([heart._pulsatile_flow(t) for t in sol.t])
    df = pd.DataFrame({
        "Time_sec": sol.t,
        "Arterial_Pressure_mmHg": sol.y[0],
        "Blood_Flow_mL_s": Q_flow,
    })
    meta = {
        "held_fixed": {},
        "note": ("No other organ required -- the two-element Windkessel "
                 "model is fully determined by R, C, HR, EDV and ESV, the "
                 "same as a coupled run's own algebraic heart step."),
        "derived": {
            "Stroke_Volume_mL": heart.SV,
            "Cardiac_Output_L_min": heart.CO,
            "Cycle_Duration_sec": heart.tc,
        },
    }
    return df, meta


# ===========================================================================
#   Lungs -- the altitude/exercise protocol only ever depended on the lungs'
#   own parameters (see human_body.py's altitude()/inspired_O2()/
#   exercise_factor(), all read only from self.p["lungs"]), so an isolated
#   lungs run needs nothing external either. These three helpers are
#   deliberately re-implemented here rather than imported from human_body.py
#   (a protected file) -- they are pure functions of `protocol_params`, not
#   bound methods of HumanBody, so there is nothing to share without either
#   modifying that file or importing a whole HumanBody just for three
#   stateless helpers.
# ===========================================================================

def _lungs_altitude_fn(protocol_params):
    target = protocol_params["altitude_target"]

    def altitude(t):
        if target == 0.0:
            return 0.0
        if t < protocol_params["ascent_start"]:
            return 0.0
        if t < protocol_params["ascent_end"]:
            frac = ((t - protocol_params["ascent_start"])
                    / max(1e-9, protocol_params["ascent_end"] - protocol_params["ascent_start"]))
            return target * frac
        if t < protocol_params["descent_start"]:
            return target
        if t < protocol_params["descent_end"]:
            frac = ((t - protocol_params["descent_start"])
                    / max(1e-9, protocol_params["descent_end"] - protocol_params["descent_start"]))
            return target + (protocol_params["altitude_after"] - target) * frac
        return protocol_params["altitude_after"]

    return altitude


def _lungs_inspired_o2_fn(constructor_params, protocol_params):
    altitude = _lungs_altitude_fn(protocol_params)
    if protocol_params["altitude_target"] == 0.0:
        pio2 = constructor_params["PiO2"]
        return lambda t: pio2
    return lambda t: float(inspired_PO2(altitude(t)))


def _lungs_exercise_fn(protocol_params):
    return lambda t: (
        protocol_params["exercise_factor"]
        if protocol_params["exercise_start"] <= t <= protocol_params["exercise_end"]
        else 1.0
    )


def run_lungs(constructor_params, protocol_params, minutes=1440.0, n_samples=None):
    lungs = LungsODE(**constructor_params)
    inspired_o2 = _lungs_inspired_o2_fn(constructor_params, protocol_params)
    exercise = _lungs_exercise_fn(protocol_params)

    o2_0, co2_0 = lungs.resting_steady_state(inspired_o2(0.0))
    y0 = [o2_0, co2_0]

    n_samples = n_samples or max(60, int(minutes))
    t_eval = np.linspace(0.0, minutes, n_samples)
    sol = lungs.simulate((0.0, minutes), t_eval, y0, exercise, inspired_o2)

    PaO2, PaCO2 = sol.y[0], sol.y[1]
    df = pd.DataFrame({
        "Time_min": sol.t,
        "PaO2_mmHg": PaO2,
        "PaCO2_mmHg": PaCO2,
        "SaO2_percent": lungs.oxygen_saturation(PaO2),
        "Altitude_m": [_lungs_altitude_fn(protocol_params)(t) for t in sol.t],
        "Inspired_O2_mmHg": [inspired_o2(t) for t in sol.t],
        "Exercise_Factor": [exercise(t) for t in sol.t],
    })
    meta = {
        "held_fixed": {"Diffusing_Capacity_scale": "1.0 (no cardiac-output coupling)"},
        "note": ("Diffusing capacity is not perfusion-scaled here -- in the "
                 "coupled body it's DL * (CO/CO_ref)**exponent, but an "
                 "isolated lungs run has no cardiac output to scale it "
                 "with, so plain DL is used throughout."),
        "derived": {},
    }
    return df, meta


# ===========================================================================
#   Liver -- needs a blood glucose input, normally the pancreas. Held
#   constant here (`test_glucose_mg_dL`), which is exactly what makes the
#   HGP/HGU switch at G_thresh visible: run it below G_thresh and the liver
#   should settle into net production, above and it should settle into net
#   uptake.
# ===========================================================================

def run_liver(constructor_params, protocol_params, test_glucose_mg_dL=90.0,
              minutes=1440.0, n_samples=None):
    liver = LiverODE(**constructor_params)
    y0 = [constructor_params["Glyc_max"] * protocol_params["glycogen_fill_initial"]]

    n_samples = n_samples or max(60, int(minutes))
    t_eval = np.linspace(0.0, minutes, n_samples)
    G_func = lambda t: test_glucose_mg_dL  # noqa: E731 -- held fixed, see module docstring

    sol = liver.simulate((0.0, minutes), t_eval, y0, G_func)
    Glyc = sol.y[0]
    HGP, HGU, Jglyc, VO2 = liver.hepatic_fluxes(np.full_like(sol.t, test_glucose_mg_dL), Glyc)

    df = pd.DataFrame({
        "Time_min": sol.t,
        "Glycogen_Mass_mg": Glyc,
        "Glycogen_Fill_Fraction": Glyc / constructor_params["Glyc_max"],
        "HGP_mg_min": HGP,
        "HGU_mg_min": HGU,
        "Jglyc_mg_min": Jglyc,
        "Hepatic_VO2_mL_min": VO2,
        "Blood_Glucose_mg_dL": test_glucose_mg_dL,
    })
    meta = {
        "held_fixed": {"Blood_Glucose_mg_dL": test_glucose_mg_dL},
        "note": ("Blood glucose held constant at %.0f mg/dL for the whole "
                 "run -- see the context slider above. G_thresh = %.0f "
                 "mg/dL is where the liver switches between net production "
                 "and net uptake." % (test_glucose_mg_dL, constructor_params["G_thresh"])),
        "derived": {},
    }
    return df, meta


# ===========================================================================
#   Kidney -- needs a perfusion pressure input, normally the heart's mean
#   arterial pressure. Held constant here (`test_MAP_mmHg`).
# ===========================================================================

def run_kidney(constructor_params, protocol_params, test_MAP_mmHg=92.0,
               minutes=1440.0, n_samples=None):
    kidney = KidneyODE(**constructor_params)

    _, _, gfr0 = kidney.renal_flows(test_MAP_mmHg)
    if protocol_params["BUN_initial"] is None:
        Mu0 = constructor_params["U_prod"] * protocol_params["Vp_initial"] / gfr0
    else:
        Mu0 = protocol_params["BUN_initial"] * 10.0 * protocol_params["Vp_initial"]
    y0 = [protocol_params["Vp_initial"], Mu0]

    def fluid_intake(t):
        return (protocol_params["drink_rate"]
                if protocol_params["drink_start"] <= t <= protocol_params["drink_end"]
                else protocol_params["baseline_intake"])

    Pa_func = lambda t: test_MAP_mmHg  # noqa: E731 -- held fixed, see module docstring

    n_samples = n_samples or max(60, int(minutes))
    t_eval = np.linspace(0.0, minutes, n_samples)
    sol = kidney.simulate((0.0, minutes), t_eval, y0, Pa_func, fluid_intake)

    Vp, Mu = sol.y[0], sol.y[1]
    _, _, GFR = kidney.renal_flows(test_MAP_mmHg)
    GFR_arr = np.full_like(sol.t, GFR)
    BUN = (Mu / Vp) * 0.1
    urine = kidney.urine_output(GFR_arr, Vp)

    df = pd.DataFrame({
        "Time_min": sol.t,
        "Plasma_Volume_L": Vp,
        "BUN_mg_dL": BUN,
        "GFR_L_min": GFR_arr,
        "Urine_Output_L_min": urine,
        "Fluid_Intake_L_min": [fluid_intake(t) for t in sol.t],
        "MAP_mmHg": test_MAP_mmHg,
    })
    meta = {
        "held_fixed": {"MAP_mmHg": test_MAP_mmHg},
        "note": ("Mean arterial pressure held constant at %.0f mmHg for the "
                 "whole run -- see the context slider above." % test_MAP_mmHg),
        "derived": {},
    }
    return df, meta


