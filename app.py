class LiverODE:
    """
    Liver ODE module using a hepatic metabolic model.

    Simulates hepatic glycogen mass and the fluxes that change it: hepatic
    glucose production (HGP) when blood glucose is low, hepatic glucose uptake
    (HGU) when it is high, the net glycogen flux Jglyc between them, and the
    hepatic oxygen consumption those fluxes require.

    The switch between production and uptake at a glucose threshold is the
    essential behaviour: it is what makes the liver the buffer that keeps blood
    glucose stable between meals, and it is the behaviour the BiLSTM surrogate
    has to reproduce.
    """

    def __init__(self, HGP_max=150.0, HGU_max=200.0, Glyc_max=100000.0,
                 G_thresh=100.0, VO2_base=50.0, alpha=0.05):
        """
        Initialise the hepatic parameters for one virtual patient.

        Parameters
        ----------
        HGP_max : float
            Maximum hepatic glucose production (mg/min), reached when blood
            glucose is far below threshold and glycogen stores are full.
        HGU_max : float
            Maximum hepatic glucose uptake (mg/min), reached when blood glucose
            is far above threshold and glycogen stores are empty.
        Glyc_max : float
            Maximum hepatic glycogen storage capacity (mg). 100,000 mg is about
            100 g, the accepted figure for an adult liver.
        G_thresh : float
            Blood glucose threshold (mg/dL) at which the liver switches from
            net production to net uptake.
        VO2_base : float
            Basal hepatic oxygen consumption (mL/min) with no glucose flux.
        alpha : float
            Oxygen cost per unit of glucose flux (mL O2 per mg glucose). Both
            producing and consuming glucose require energy, so the magnitude of
            the flux, not its sign, drives the additional demand.
        """
        self.HGP_max = HGP_max
        self.HGU_max = HGU_max
        self.Glyc_max = Glyc_max
        self.G_thresh = G_thresh
        self.VO2_base = VO2_base
        self.alpha = alpha

    # ------------------------------------------------------------------
    # Shared flux relations
    # ------------------------------------------------------------------

    def hepatic_fluxes(self, G, Glyc):
        """
        Hepatic glucose fluxes at a given blood glucose and glycogen mass.

        This is the single definition of the flux relations. Both the ODE
        right-hand side and the synthetic-data output columns call it, so the
        saved dataset is guaranteed to be consistent with what was integrated.
        Written with `numpy.where` rather than an `if`, so it accepts scalars
        from the solver and whole arrays from the post-processing step.

        Parameters
        ----------
        G : float or ndarray
            Blood glucose concentration (mg/dL) arriving from the circulation.
        Glyc : float or ndarray
            Current hepatic glycogen mass (mg).

        Returns
        -------
        HGP, HGU, Jglyc, VO2
            Hepatic glucose production (mg/min), hepatic glucose uptake
            (mg/min), net glycogen flux (mg/min, positive = storing), and
            hepatic oxygen consumption (mL/min).
        """
        # Fractional fullness of the glycogen store, bounded to [0, 1]. This is
        # what makes the fluxes self-limiting: a full liver cannot take up more
        # glucose, and an empty one cannot release any.
        Glyc_ratio = np.clip(np.asarray(Glyc, dtype=float) / self.Glyc_max, 0.0, 1.0)
        G = np.asarray(G, dtype=float)

        above = G > self.G_thresh

        # Uptake, active only above threshold. The Michaelis-Menten-like term
        # (G - G_thresh)/(G + 50) saturates as glucose rises, and the
        # (1 - Glyc_ratio) term shuts uptake down as the store fills.
        HGU = np.where(
            above,
            self.HGU_max * ((G - self.G_thresh) / (G + 50.0)) * (1.0 - Glyc_ratio),
            0.0,
        )

        # Production, active only below threshold. Scales with how far glucose
        # has fallen below threshold, and with how much glycogen is left to
        # mobilise.
        HGP = np.where(
            above,
            0.0,
            self.HGP_max * ((self.G_thresh - G) / self.G_thresh) * Glyc_ratio,
        )

        # Net glycogen flux: what goes in minus what comes out.
        Jglyc = HGU - HGP

        # Oxygen demand rises with the absolute size of the flux, since both
        # glycogenesis and glycogenolysis are energy-requiring.
        VO2 = self.VO2_base + self.alpha * (HGU + HGP)

        return HGP, HGU, Jglyc, VO2

    # ------------------------------------------------------------------
    # ODE system
    # ------------------------------------------------------------------

    def _hepatic_odes(self, t, y, G_func):
        """
        Right-hand side of the hepatic ODE system.

        State variable (y)
        ------------------
        y[0] = Glyc(t) : hepatic glycogen mass (mg)

        External (coupled) input
        ------------------------
        G_func : callable
            Blood glucose concentration (mg/dL) at time t. Supplied by the
            pancreas module once the organs are coupled; a prescribed fasting
            curve during isolated testing.
        """
        Glyc = y[0]
        G = G_func(t)

        # The net glycogen flux *is* the rate of change of the store.
        _, _, Jglyc, _ = self.hepatic_fluxes(G, Glyc)
        return [float(Jglyc)]

    def simulate(self, t_span, t_eval, y0, G_func):
        """
        Integrate the hepatic ODE system for a single virtual patient.

        `max_step` is capped because the HGP/HGU switch at G_thresh is a kink in
        the right-hand side. Limiting the step size keeps the solver from
        overshooting the crossing and smearing the transition.

        30 minutes was chosen by comparison against a 5-minute cap: the final
        glycogen mass agrees to within 0.1 mg over a 24-hour fast, while the run
        is about twelve times faster. Leaving the cap off entirely does shift the
        answer (by about 100 mg), so some ceiling is needed.
        """
        solution = solve_ivp(
            fun=self._hepatic_odes,
            t_span=t_span,
            y0=y0,
            t_eval=t_eval,
            args=(G_func,),
            method='RK45',
            max_step=30.0,
        )
        return solution

    # ------------------------------------------------------------------
    # Cohort generation (WBS 3.3)
    # ------------------------------------------------------------------

    def generate_synthetic_cohort(self, num_patients=1000, t_max=1440, n_samples=1440,
                                  G_start=110.0, G_floor=70.0, G_fall_minutes=600.0,
                                  initial_fill=0.8):
        """
        Generate a synthetic cohort of virtual patients under a fasting protocol.

        Every patient is given a declining blood-glucose input representing a
        prolonged fast: glucose falls linearly from its starting value to a
        floor over the first ten hours, then holds. The liver therefore begins
        in net uptake, crosses the threshold, and switches to net production for
        the remainder of the record. That crossing is the feature of interest.

        Per-patient variation covers glycogen capacity and maximum production
        rate, which together span the range from a healthy liver to one with
        reduced storage such as in hepatic steatosis, plus the starting glucose
        of the fasting curve.

        Parameters
        ----------
        num_patients : int
            Number of virtual patients in the cohort.
        t_max : float
            Simulation length in minutes; 1440 gives a 24-hour record.
        n_samples : int
            Number of output samples per patient; 1440 gives one per minute.
        G_start : float
            Nominal blood glucose at t = 0 (mg/dL), before per-patient variation.
        G_floor : float
            Blood glucose floor reached at the end of the fall (mg/dL).
        G_fall_minutes : float
            Duration of the linear fall (minutes).
        initial_fill : float
            Initial glycogen store as a fraction of that patient's capacity.

        Returns
        -------
        pandas.DataFrame
            Long-format cohort, one row per patient per sample.
        """
        all_data = []

        t_eval = np.linspace(0, t_max, n_samples)
        t_span = (0.0, t_max)

        for patient_id in range(num_patients):
            # --- per-patient physiological variation ------------------------
            Glyc_max_var = np.random.normal(self.Glyc_max, self.Glyc_max * 0.10)
            HGP_max_var = np.random.normal(self.HGP_max, self.HGP_max * 0.10)
            G_start_var = np.random.normal(G_start, G_start * 0.05)

            # Clip to physiological bands so the Gaussian tail cannot produce a
            # liver with negative storage capacity.
            Glyc_max_var = float(np.clip(Glyc_max_var, 0.5 * self.Glyc_max, 1.5 * self.Glyc_max))
            HGP_max_var = float(np.clip(HGP_max_var, 0.5 * self.HGP_max, 1.5 * self.HGP_max))
            G_start_var = float(np.clip(G_start_var, 90.0, 130.0))

            temp_liver = LiverODE(HGP_max=HGP_max_var, HGU_max=self.HGU_max,
                                  Glyc_max=Glyc_max_var, G_thresh=self.G_thresh,
                                  VO2_base=self.VO2_base, alpha=self.alpha)

            # --- prescribed blood glucose input ------------------------------
            # Linear fall from this patient's starting glucose to the floor over
            # `G_fall_minutes`, then constant. `slope` is captured per patient so
            # the curve differs across the cohort. Defined as a closure over
            # loop-local values, which is safe here because the solver is run to
            # completion before the next iteration begins.
            slope = (G_start_var - G_floor) / G_fall_minutes

            def G_dist(t, _G0=G_start_var, _slope=slope, _floor=G_floor):
                """Blood glucose (mg/dL) arriving from the circulation."""
                return max(_floor, _G0 - _slope * t)

            # --- initial state ----------------------------------------------
            y0 = [Glyc_max_var * initial_fill]

            sol = temp_liver.simulate(t_span, t_eval, y0, G_dist)

            # --- derived output columns --------------------------------------
            # Vectorised: the glucose input is evaluated on the output grid, then
            # all four fluxes come from one call to the shared method.
            Glyc_array = sol.y[0]
            G_array = np.maximum(G_floor, G_start_var - slope * sol.t)
            HGP_array, HGU_array, Jglyc_array, VO2_array = temp_liver.hepatic_fluxes(
                G_array, Glyc_array
            )

            df = pd.DataFrame({
                'Patient_ID': patient_id,
                'Time_min': sol.t,
                'Blood_Glucose_mg_dL': G_array,
                'Glycogen_Mass_mg': Glyc_array,
                'Glycogen_Fill_Fraction': Glyc_array / Glyc_max_var,
                'HGP_mg_min': HGP_array,
                'HGU_mg_min': HGU_array,
                'Jglyc_mg_min': Jglyc_array,
                'Hepatic_VO2_mL_min': VO2_array,
            })
            all_data.append(df)

        return pd.concat(all_data, ignore_index=True)


