class KidneyODE:
    """
    Kidney ODE module using a simplified Guyton filtration model.

    Simulates glomerular filtration rate (GFR), whole-body fluid balance via
    plasma volume, and urea clearance expressed as blood urea nitrogen (BUN).

    The model is deliberately low-order: it captures the pressure -> flow ->
    filtration -> excretion chain that couples the kidney to the heart and to
    the blood compartment, without resolving individual nephron segments. That
    level of detail is what the downstream BiLSTM surrogate is expected to learn
    from data rather than to reproduce from first principles.
    """

    def __init__(self, RVR=80.0, FF=0.20, Hct=0.45, f_reab=0.9928,
                 Vp_ref=3.0, U_prod=12.0):
        """
        Initialise the renal parameters for one virtual patient.

        Parameters
        ----------
        RVR : float
            Renal vascular resistance (mmHg*min/L). With a mean arterial
            pressure of 100 mmHg this gives renal blood flow of
            100/80 = 1.25 L/min, the accepted physiological value (roughly
            20-25% of cardiac output).
        FF : float
            Filtration fraction (dimensionless). Fraction of renal *plasma*
            flow that crosses the glomerular membrane; normally about 0.20.
        Hct : float
            Haematocrit (dimensionless). Fraction of blood volume occupied by
            red cells, used to convert renal blood flow to renal plasma flow,
            since only plasma is filtered.
        f_reab : float
            Baseline tubular reabsorption fraction (dimensionless) at the
            reference plasma volume. About 99.3% of the filtered volume is
            reabsorbed along the tubule, so only the small remainder appears as
            urine. At GFR = 0.1375 L/min this yields roughly 1 mL/min of urine,
            i.e. about 1.4 L/day.
        Vp_ref : float
            Reference (set-point) plasma volume (L) for an average adult. Acts
            as the target of the volume feedback on reabsorption.
        U_prod : float
            Whole-body urea production rate (mg/min), the nitrogenous load the
            kidney has to clear. About 12 mg/min corresponds to ~17 g/day.
        """
        self.RVR = RVR
        self.FF = FF
        self.Hct = Hct
        self.f_reab = f_reab
        self.Vp_ref = Vp_ref
        self.U_prod = U_prod

    # ------------------------------------------------------------------
    # Algebraic helper relations
    # ------------------------------------------------------------------

    def renal_flows(self, Pa):
        """
        Convert arterial pressure to renal blood flow, plasma flow and GFR.

        Kept as a separate method so the synthetic-data step can reproduce the
        same numbers for its output columns without duplicating the formulae the
        ODE right-hand side uses.

        Parameters
        ----------
        Pa : float or ndarray
            Mean arterial pressure (mmHg).

        Returns
        -------
        RBF, RPF, GFR : same shape as `Pa`
            Renal blood flow, renal plasma flow and glomerular filtration rate,
            all in L/min.
        """
        RBF = Pa / self.RVR              # Ohm's law analogue: flow = pressure / resistance
        RPF = RBF * (1.0 - self.Hct)     # only the plasma fraction reaches the filter
        GFR = RPF * self.FF              # filtration fraction acts on plasma flow
        return RBF, RPF, GFR

    def reabsorption_fraction(self, Vp):
        """
        Tubular reabsorption fraction with negative feedback on plasma volume.

        Physiological basis: when plasma volume rises above its set point, ADH
        secretion falls and the collecting duct reabsorbs less water, so urine
        output increases; when volume falls, the opposite happens. Expressing
        reabsorption as a fraction of the filtered load (rather than as a fixed
        absolute maximum) also removes the numerical problem in the original
        version, where urine output was the difference between two nearly equal
        quantities and was therefore extremely sensitive to parameter noise.

        The result is clipped to a plausible band so a transient volume
        excursion can never drive reabsorption to a non-physiological value.
        """
        frac = self.f_reab * (self.Vp_ref / Vp)
        return np.clip(frac, 0.95, 0.999)

    def urine_output(self, GFR, Vp):
        """Urine flow (L/min): the filtered volume that is not reabsorbed."""
        return GFR * (1.0 - self.reabsorption_fraction(Vp))

    # ------------------------------------------------------------------
    # ODE system
    # ------------------------------------------------------------------

    def _guyton_odes(self, t, y, Pa_func, fluid_in_func):
        """
        Right-hand side of the renal ODE system.

        State variables (y)
        -------------------
        y[0] = Vp(t) : plasma volume (L)
        y[1] = Mu(t) : mass of blood urea nitrogen in the plasma pool (mg)

        External (coupled) inputs
        -------------------------
        Pa_func : callable
            Mean arterial pressure (mmHg) at time t. Supplied by the heart
            module once the organs are coupled; a constant during isolated
            testing.
        fluid_in_func : callable
            Fluid intake rate (L/min) at time t, covering both drinking events
            and baseline metabolic water production.
        """
        Vp, Mu = y

        # Guard against the solver probing a non-physical state during step
        # rejection, which would otherwise divide by zero below.
        Vp = max(Vp, 0.5)

        # --- external inputs at this instant --------------------------------
        Pa = Pa_func(t)
        fluid_in = fluid_in_func(t)

        # --- 1. pressure -> flow -> filtration ------------------------------
        _, _, GFR = self.renal_flows(Pa)

        # --- 2. plasma volume balance ---------------------------------------
        # Water in (drinking plus metabolic production) minus water out (urine).
        # Insensible losses through skin and breath are folded into the baseline
        # intake term rather than modelled separately.
        dVp_dt = fluid_in - self.urine_output(GFR, Vp)

        # --- 3. urea balance -------------------------------------------------
        # Urea is produced at a constant whole-body rate and cleared by
        # filtration in proportion to its plasma concentration. This is a
        # single-pool approximation: tubular reabsorption of urea is absorbed
        # into the effective clearance rather than modelled explicitly.
        urea_concentration = Mu / Vp                    # mg/L
        urea_clearance = GFR * urea_concentration       # mg/min
        dMu_dt = self.U_prod - urea_clearance

        return [dVp_dt, dMu_dt]

    def simulate(self, t_span, t_eval, y0, Pa_func, fluid_in_func):
        """
        Integrate the renal ODE system for a single virtual patient.

        `max_step` is capped so the adaptive solver cannot step straight over
        the fluid-intake window, which is only 10 minutes wide inside a 24-hour
        simulation.
        """
        solution = solve_ivp(
            fun=self._guyton_odes,
            t_span=t_span,
            y0=y0,
            t_eval=t_eval,
            args=(Pa_func, fluid_in_func),
            method='RK45',
            max_step=5.0,
        )
        return solution

    # ------------------------------------------------------------------
    # Cohort generation (WBS 3.5)
    # ------------------------------------------------------------------

    def generate_synthetic_cohort(self, num_patients=1000, t_max=1440, n_samples=1440,
                                  Pa_baseline=100.0, drink_start=120.0, drink_end=130.0,
                                  drink_rate=0.05, baseline_intake=0.001):
        """
        Generate a synthetic cohort of virtual patients.

        Each patient is one solution of the renal model with slightly different
        physiology, so the cohort spans the spread found across a real
        population. Every patient receives the same fluid-intake schedule: a low
        baseline representing metabolic water production, plus a single drinking
        event two hours into the simulation.

        Parameters
        ----------
        num_patients : int
            Number of virtual patients in the cohort.
        t_max : float
            Simulation length in minutes. Defaults to 1440 (24 h) so the
            timebase matches the pancreas, liver and lungs modules.
        n_samples : int
            Number of output samples per patient; 1440 gives one per minute.
        Pa_baseline : float
            Mean arterial pressure (mmHg) held constant during isolated
            testing. Replaced by the heart module's output once coupled.
        drink_start, drink_end : float
            Start and end of the drinking event (minutes).
        drink_rate : float
            Fluid intake rate during the event (L/min). 0.05 L/min over
            10 minutes delivers 500 mL.
        baseline_intake : float
            Fluid intake rate outside the event (L/min), representing metabolic
            water production.

        Returns
        -------
        pandas.DataFrame
            Long-format cohort, one row per patient per sample.
        """
        all_data = []

        # Uniform output grid. Using `n_samples` explicitly, rather than reusing
        # `t_max` as the sample count, keeps the sampling interval independent
        # of the simulation length.
        t_eval = np.linspace(0, t_max, n_samples)
        t_span = (0.0, t_max)

        # Dynamic inputs. Defined once outside the patient loop because they
        # describe the experimental protocol, not the patient.
        def Pa_dist(t):
            """Mean arterial pressure (mmHg). Constant while the kidney is
            simulated in isolation; becomes the heart module's arterial
            pressure once the organs are coupled."""
            return Pa_baseline

        def fluid_in_dist(t):
            """Fluid intake rate (L/min): a 500 mL drink over the event window,
            baseline metabolic water production otherwise."""
            return drink_rate if drink_start <= t <= drink_end else baseline_intake

        for patient_id in range(num_patients):
            # --- per-patient physiological variation ------------------------
            # 10% on resistance (a higher RVR represents mild renal
            # hypoperfusion) and 5% on filtration fraction, which is the more
            # tightly regulated of the two.
            RVR_var = np.random.normal(self.RVR, self.RVR * 0.10)
            FF_var = np.random.normal(self.FF, self.FF * 0.05)

            # Keep the draws inside a physiological band. Without this the tail
            # of the Gaussian can occasionally produce a negative resistance or
            # filtration fraction.
            RVR_var = float(np.clip(RVR_var, 0.5 * self.RVR, 1.5 * self.RVR))
            FF_var = float(np.clip(FF_var, 0.10, 0.35))

            temp_kidney = KidneyODE(RVR=RVR_var, FF=FF_var, Hct=self.Hct,
                                    f_reab=self.f_reab, Vp_ref=self.Vp_ref,
                                    U_prod=self.U_prod)

            # --- initial state ----------------------------------------------
            # Plasma volume starts at the adult reference value. Initial urea
            # mass is set to the steady state implied by this patient's own GFR
            # (Mu* = U_prod * Vp / GFR), so the record does not open with a
            # large artificial transient while urea settles.
            _, _, GFR0 = temp_kidney.renal_flows(Pa_baseline)
            Vp0 = self.Vp_ref
            Mu0 = self.U_prod * Vp0 / GFR0
            y0 = [Vp0, Mu0]

            sol = temp_kidney.simulate(t_span, t_eval, y0, Pa_dist, fluid_in_dist)

            # --- derived output columns --------------------------------------
            # Recomputed on the solution grid using the same helper methods the
            # ODE used, so the saved columns are exactly consistent with the
            # integrated states.
            Pa_array = np.full_like(sol.t, Pa_baseline, dtype=float)
            _, _, GFR_array = temp_kidney.renal_flows(Pa_array)

            Vp_array = sol.y[0]
            Mu_array = sol.y[1]

            urine_array = temp_kidney.urine_output(GFR_array, Vp_array)

            # Urea mass (mg) divided by plasma volume (L) gives mg/L; the factor
            # 0.1 converts to the clinical unit mg/dL.
            BUN_array = (Mu_array / Vp_array) * 0.1

            df = pd.DataFrame({
                'Patient_ID': patient_id,
                'Time_min': sol.t,
                'Plasma_Volume_L': Vp_array,
                'GFR_L_min': GFR_array,
                'Urine_Output_L_min': urine_array,
                'BUN_mg_dL': BUN_array,
                'Renal_Vascular_Resistance': RVR_var,
            })
            all_data.append(df)

        return pd.concat(all_data, ignore_index=True)


