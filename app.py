def run_with(overrides, minutes=1440.0, base=None):
    """
    Run the body with some parameters changed.

    `overrides` is {organ: {parameter: value}}, for example
    {"kidney": {"RVR": 120.0}, "heart": {"HR": 90.0}}.
    """
    p = copy.deepcopy(base if base is not None else PARAMETERS)
    for organ, changes in overrides.items():
        if organ not in p:
            raise KeyError("No such section in PARAMETERS: %r. Valid sections: %s"
                           % (organ, list(p)))
        for key, value in changes.items():
            if key not in p[organ]:
                raise KeyError("No parameter %r in section %r. Valid: %s"
                               % (key, organ, list(p[organ])))
            p[organ][key] = value
    return HumanBody(p).run(minutes=minutes)


def compare_parameter(organ, parameter, values, minutes=720.0, watch=None):
    """
    Sweep one parameter and report what it did to every organ.

    This is the headline capability of the coupled model: change renal
    resistance and watch mean arterial pressure, glucose and blood urea move
    together, none of which the isolated kidney model could have told you.

    Returns a DataFrame with one row per value tested and one column per
    watched variable, holding the value at the end of the run.
    """
    watch = watch or ["MAP_mmHg", "Cardiac_Output_L_min", "PaO2_mmHg", "PaCO2_mmHg",
                      "Glucose_mg_dL", "Glycogen_Fill_Fraction",
                      "Plasma_Volume_L", "BUN_mg_dL", "GFR_L_min"]

    rows = []
    for v in values:
        df = run_with({organ: {parameter: v}}, minutes=minutes)
        row = {"%s.%s" % (organ, parameter): v}
        row.update({c: float(df[c].iloc[-1]) for c in watch})
        rows.append(row)

    return pd.DataFrame(rows)


