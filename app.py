#   only), same as `PancreasODE.generate_synthetic_cohort`.
# ===========================================================================

def run_pancreas(constructor_params, protocol_params, minutes=1440.0, n_samples=None):
    pancreas = PancreasODE(**constructor_params)
    y0 = [protocol_params["G_initial"], protocol_params["X_initial"], protocol_params["I_initial"]]

    def meal_Ra(t):
        return (protocol_params["meal_Ra"]
                if protocol_params["meal_start"] <= t <= protocol_params["meal_end"] else 0.0)

    n_samples = n_samples or max(60, int(minutes))
    t_eval = np.linspace(0.0, minutes, n_samples)
    sol = pancreas.simulate((0.0, minutes), t_eval, y0, meal_Ra)

    df = pd.DataFrame({
        "Time_min": sol.t,
        "Glucose_mg_dL": sol.y[0],
        "Insulin_Action_1_min": sol.y[1],
        "Insulin_uU_mL": sol.y[2],
        "Meal_Ra_mg_min": [meal_Ra(t) for t in sol.t],
    })
    meta = {
        "held_fixed": {},
        "note": ("No other organ required -- the Bergman minimal model is "
                 "driven only by the gut meal input, which this organ's own "
                 "protocol already fully specifies."),
        "derived": {},
    }
    return df, meta


