class PancreasODE:
    """
    Pancreas ODE Module using the Bergman Minimal Model.
    Simulates glucose and insulin dynamics to generate synthetic time-series data.
    """
    
    def __init__(self, Gb=90.0, Ib=15.0, p1=0.028, p2=0.025, 
                 p3=0.00013, n=0.13, gamma=0.004, h=79.0, V=12.0):
        """
        Initializes the physiological parameters (constants) for the virtual patient.
        
        Parameters:
        -----------
        Gb (float):    Basal plasma glucose (mg/dL). Resting, fasting baseline.
        Ib (float):    Basal plasma insulin (uU/mL). Resting, fasting baseline.
        p1 / Sg (float): Glucose effectiveness (1/min). Clearance of glucose independent of active insulin.
        p2 (float):    Insulin action decrease rate (1/min). Rate at which active insulin degrades.
        p3 (float):    Insulin action magnitude (1/min^2 per uU/mL). Rate plasma insulin enters interstitial fluid.
        n (float):     Insulin clearance rate (1/min). Fractional rate at which insulin is cleared from blood.
        gamma (float): Beta-cell sensitivity (uU/mL per min^2 (mg/dL)). Pancreatic secretion response to glucose.
        h (float):     Glucose threshold (mg/dL). Blood sugar level that triggers insulin secretion.
        V (float):     Distribution volume (dL/kg). Volume of fluid into which glucose is distributed.
        """
        self.Gb = Gb
        self.Ib = Ib
        self.p1 = p1
        self.p2 = p2
        self.p3 = p3
        self.n = n
        self.gamma = gamma
        self.h = h
        self.V = V

    def _bergman_odes(self, t, y, Ra_func):
        """
        The system of Ordinary Differential Equations (ODEs) for the Pancreas.
        
        State Variables (y):
        --------------------
        y[0] = G(t): Plasma Glucose Concentration (mg/dL).
        y[1] = X(t): Insulin Action (1/min). Active insulin in interstitial fluid.
        y[2] = I(t): Plasma Insulin Concentration (uU/mL).
        
        Inputs:
        -------
        t (float): Current time step in minutes.
        y (list): Current values of the state variables [G, X, I].
        Ra_func (callable): Function returning the Rate of Glucose Appearance (mg/min) at time t.
        """
        G, X, I = y
        Ra = Ra_func(t) 

        # 1. Glucose Dynamics: dG(t)/dt = -[p1 + X(t)]*G(t) + p1*Gb + Ra(t)/V
        dG_dt = -(self.p1 + X) * G + self.p1 * self.Gb + (Ra / self.V)
        
        # 2. Insulin Action Dynamics: dX(t)/dt = -p2*X(t) + p3*[I(t) - Ib]
        dX_dt = -self.p2 * X + self.p3 * (I - self.Ib)
        
        # 3. Insulin Secretion and Clearance: dI(t)/dt = -n*[I(t) - Ib] + gamma*[G(t) - h]*t
        # Secretion only occurs if Glucose is above the pancreatic threshold 'h'
        #
        # KNOWN ISSUE (identified 06 Aug 2026, carried forward to M2 validation)
        # ---------------------------------------------------------------------
        # The trailing factor of `t` is taken from Bergman's original IVGTT
        # formulation, where t is the time elapsed *since the glucose bolus* and
        # only ever reaches a few tens of minutes. Here t is absolute simulation
        # time and runs to 1440 min, so the secretion term is scaled by up to
        # 1440 instead of by tens. That is why plasma insulin peaks near
        # 146 uU/mL and why glucose is driven down below the hypoglycaemic
        # threshold in some virtual patients, which is the limitation recorded in
        # logs/3_1_synthetic_pancreas_log.txt.
        #
        # The correction is to make the factor a time measured from the start of
        # the current glucose excursion, or to drop it and re-fit gamma. Either
        # route changes the glucose and insulin scales together, so it has to be
        # done alongside the real-data calibration in M2 rather than in
        # isolation. Left unchanged here so that the WBS 3.1 dataset, its log and
        # the Chapter 3 write-up remain consistent with the code that produced
        # them.
        secretion = self.gamma * (G - self.h) * t if G > self.h else 0.0
        dI_dt = -self.n * (I - self.Ib) + secretion

        return [dG_dt, dX_dt, dI_dt]

    def simulate(self, t_span, t_eval, y0, Ra_func):
        """
        Solves the ODE system for a single virtual patient over a given time span.
        """
        solution = solve_ivp(
            fun=self._bergman_odes,
            t_span=t_span,
            y0=y0,
            t_eval=t_eval,
            args=(Ra_func,),
            method='RK45'
        )
        return solution

    def generate_synthetic_cohort(self, num_patients=1000, t_max=1440):
        """
        Generates a synthetic time-series dataset by introducing Gaussian noise 
        to parameters for multiple 'virtual patients'. Defaults to a 24-hour simulation.
        """
        all_data = []
        t_eval = np.linspace(0, t_max, t_max)
        t_span = (0, t_max)

        for patient_id in range(num_patients):
            # Inject 10% physiological variance (Gaussian noise) to simulate real-world diversity
            Gb_var = np.random.normal(self.Gb, self.Gb * 0.1)
            Ib_var = np.random.normal(self.Ib, self.Ib * 0.1)
            
            # Initial states: G0 (baseline glucose), X0 (zero active insulin), I0 (baseline insulin)
            y0 = [Gb_var, 0.0, Ib_var] 

            # Define a simple meal disturbance at t=300 (5 hours in) lasting for 60 minutes
            def meal_disturbance(t):
                return 50.0 if 300 <= t <= 360 else 0.0

            # Run simulation
            sol = self.simulate(t_span, t_eval, y0, meal_disturbance)

            # Structure output data into a DataFrame
            df = pd.DataFrame({
                'Patient_ID': patient_id,
                'Time_min': sol.t,
                'Glucose_mg_dL': sol.y[0],
                'Insulin_Action_1_min': sol.y[1],
                'Insulin_uU_mL': sol.y[2]
            })
            all_data.append(df)

        return pd.concat(all_data, ignore_index=True)

