def barometric_pressure(altitude_m):
    """
    Barometric pressure (mmHg) at a given altitude, from the International
    Standard Atmosphere troposphere model.

        P = P0 * (1 - 2.25577e-5 * h) ** 5.25588

    Valid to about 11,000 m. Above that the troposphere assumption fails and the
    formula under-predicts; the model is not intended for that range and the
    cohort tops out at 5,500 m.

    Check values: 0 m -> 760 mmHg, 2500 m -> 560, 4000 m -> 462, 5500 m -> 379.
    """
    h = np.asarray(altitude_m, dtype=float)
    return P0_SEA_LEVEL * np.power(1.0 - 2.25577e-5 * h, 5.25588)


def inspired_PO2(altitude_m):
    """
    Inspired oxygen partial pressure (mmHg) at a given altitude.

        PiO2 = FiO2 * (PB - PH2O)

    Water vapour is subtracted because inspired air is fully humidified by the
    time it reaches the alveoli, and that 47 mmHg does not scale with altitude -
    which is why hypoxia worsens faster than barometric pressure alone suggests.

    Check values: 0 m -> 149 mmHg, 4000 m -> 87, 5500 m -> 70.
    """
    return FIO2_AIR * (barometric_pressure(altitude_m) - PH2O_BODY)


class LungsODE:
    """
    Lungs ODE module for pulmonary gas exchange.

    Simulates arterial oxygen and carbon dioxide tensions using Fick's law of
    diffusion for oxygen, the alveolar gas equation to couple the two, and the
    alveolar ventilation equation for carbon dioxide. Ventilation responds to
    hypoxaemia, which is what allows the module to be used at altitude.

    Calibration. The defaults for resting ventilation, diffusing capacity, the
    hypoxic response gain and the recruitment gain were fitted by least squares
    against standard reference values for acute altitude exposure at 0, 2500,
    4000 and 5500 m (arterial oxygen, arterial CO2 and haemoglobin saturation at
    each). Sea level lands almost exactly - 95.2 mmHg, 39.2 mmHg, 96.8% against
    references of 95, 40 and 97%. Above 4000 m the model is systematically
    pessimistic by roughly 3-4 mmHg of oxygen and 6 percentage points of
    saturation, because a two-state model with a linear hypoxic response cannot
    capture the way the dissociation curve steepens. It is fit for comparing
    altitudes and for training a surrogate; it should not be read as a predictor
    of an individual's saturation at a given altitude. This residual bias is
    recorded as a limitation.

    Note also that this is ACUTE exposure only. Acclimatisation - renal
    bicarbonate excretion compensating the respiratory alkalosis, and the rise in
    haemoglobin over days to weeks - is not modelled, and the bicarbonate half of
    that was lost with the retired blood module. Simulations should be read as
    hours at altitude, not days.

    Unit note. The relaxation time of each state is set by Vcap, a blood volume
    in mL, divided by flows in mL/min (oxygen) and L/min (carbon dioxide). The
    mixed units mean the model reproduces the correct steady state for both gases
    but its transient time constants are only order-of-magnitude correct. This is
    acceptable because the synthetic data is used to teach the surrogate the shape
    of the response, but it means the model should not be used to study the
    *speed* of acclimatisation. Recorded as a limitation.
    """

    def __init__(self, PiO2=149.2, VA=4.4, DL=50.0, VO2=250.0, VCO2=200.0,
                 RQ=0.8, Vcap=70.0,
                 hvr_gain=1.8, hvr_threshold=65.0, hvr_max=4.0,
                 recruit_gain=1.3, P50=26.8, hill_n=2.7):
        """
        Initialise the respiratory parameters for one virtual patient.

        Parameters
        ----------
        PiO2 : float
            Inspired oxygen partial pressure (mmHg) when no altitude profile is
            supplied. 149.2 corresponds to sea level.
        VA : float
            Resting alveolar ventilation (L/min), before any hypoxic drive.
        DL : float
            Diffusing capacity of the lung for oxygen (mL/min/mmHg).
        VO2 : float
            Whole-body oxygen consumption (mL/min) at rest.
        VCO2 : float
            Whole-body carbon dioxide production (mL/min) at rest.
        RQ : float
            Respiratory quotient, VCO2/VO2, about 0.8 on a mixed diet.
        Vcap : float
            Pulmonary capillary blood volume (mL).
        hvr_gain : float
            Hypoxic ventilatory response gain (dimensionless). Ventilation is
            multiplied by (1 + hvr_gain * hypoxic fraction). This varies several
            fold between individuals and is one of the better predictors of who
            tolerates altitude, so it is treated as a per-patient parameter.
        hvr_threshold : float
            PaO2 (mmHg) below which the hypoxic drive engages. The carotid body
            response is minimal above roughly 60-70 mmHg and steepens sharply
            below it.
        hvr_max : float
            Ceiling on the ventilatory multiplier. Ventilation cannot rise
            without limit; mechanical and fatigue limits cap it.
        recruit_gain : float
            Pulmonary capillary recruitment gain (dimensionless). Effective
            diffusing capacity rises alongside the hypoxic and metabolic drive,
            because hypoxic pulmonary vasoconstriction redistributes flow and
            raises cardiac output, recruiting capillaries that were closed at
            rest. Measured diffusing capacity does rise at altitude and during
            exercise, and without this term the model over-predicts desaturation
            in both. Set to 0.0 to recover the r1 fixed-capacity behaviour.
        P50 : float
            Oxygen tension (mmHg) at 50% haemoglobin saturation.
        hill_n : float
            Hill coefficient for oxygen binding cooperativity.
        """
        self.PiO2 = PiO2
        self.VA = VA
        self.DL = DL
        self.VO2 = VO2
        self.VCO2 = VCO2
        self.RQ = RQ
        self.Vcap = Vcap

        self.hvr_gain = hvr_gain
        self.hvr_threshold = hvr_threshold
        self.hvr_max = hvr_max
        self.recruit_gain = recruit_gain

        self.P50 = P50
        self.hill_n = hill_n

        # Conversion constant in the alveolar ventilation equation,
        # PaCO2 = K * VCO2 / VA.
        self.K = 0.863

    # ------------------------------------------------------------------
    # Algebraic relations
    # ------------------------------------------------------------------

    def alveolar_PO2(self, PaCO2, PiO2=None):
        """
        Alveolar oxygen tension (mmHg) from the alveolar gas equation.

            PAO2 = PiO2 - PaCO2 / RQ

        Clipped at zero: at extreme altitude the arithmetic can go negative,
        which is not a physiological state but a signal that the model has been
        pushed past its range.
        """
        PiO2 = self.PiO2 if PiO2 is None else PiO2
        return np.maximum(0.0, PiO2 - PaCO2 / self.RQ)

    def hypoxic_drive(self, PaO2):
        """
        Ventilatory multiplier from the hypoxic ventilatory response.

        Returns 1.0 when oxygenation is adequate, rising as PaO2 falls below the
        threshold:

            multiplier = 1 + gain * (threshold - PaO2) / threshold

        capped at `hvr_max`. This is a phenomenological description of carotid
        body output rather than a receptor model, which is the appropriate level
        of detail here: the shape of the response is what matters for the
        surrogate, and a receptor model would add parameters that cannot be
        identified from the data available.
        """
        deficit = np.maximum(0.0, self.hvr_threshold - np.asarray(PaO2, dtype=float))
        mult = 1.0 + self.hvr_gain * (deficit / self.hvr_threshold)
        return np.minimum(mult, self.hvr_max)

    def effective_DL(self, drive):
        """
        Effective diffusing capacity (mL/min/mmHg) for a given ventilatory drive.

            DL_eff = DL * (1 + recruit_gain * (drive - 1))

        `drive` is the combined hypoxic and metabolic multiplier, so recruitment
        follows both altitude and exercise. Physiologically this stands in for
        capillary recruitment: at rest a substantial fraction of the pulmonary
        capillary bed is closed, and it opens as pulmonary artery pressure and
        cardiac output rise. Holding capacity fixed instead makes the
        alveolar-arterial gradient scale directly with oxygen demand, which
        over-predicts desaturation both at altitude and during exercise.
        """
        return self.DL * (1.0 + self.recruit_gain * (np.asarray(drive, dtype=float) - 1.0))

    def oxygen_saturation(self, PaO2):
        """
        Haemoglobin oxygen saturation (%) from the Hill equation.

            SaO2 = 100 * PaO2^n / (PaO2^n + P50^n)

        This is the quantity a pulse oximeter reports, and therefore the one that
        can actually be checked against a measurement at altitude. It is also the
        relation that used to live in the retired blood module; it belongs here,
        with the organ that sets PaO2.

        Check values: PaO2 90 -> 96%, PaO2 50 -> 84%, PaO2 35 -> 66%.
        """
        p = np.maximum(0.0, np.asarray(PaO2, dtype=float))
        return 100.0 * (p ** self.hill_n) / (p ** self.hill_n + self.P50 ** self.hill_n)

    # ------------------------------------------------------------------
    # ODE system
    # ------------------------------------------------------------------

    def _respiratory_odes(self, t, y, exercise_multiplier_func, PiO2_func=None):
        """
        Right-hand side of the pulmonary ODE system.

        State variables (y)
        -------------------
        y[0] = PaO2(t)  : arterial oxygen tension (mmHg)
        y[1] = PaCO2(t) : arterial carbon dioxide tension (mmHg)

        External inputs
        ---------------
        exercise_multiplier_func : callable
            Scales metabolic demand and ventilation together. 1.0 is rest.
        PiO2_func : callable, optional
            Inspired oxygen tension (mmHg) at time t, which is how an altitude
            profile enters the model. Constant at `self.PiO2` if omitted.
        """
        PaO2, PaCO2 = y

        PiO2 = self.PiO2 if PiO2_func is None else PiO2_func(t)

        # --- exercise: demand and ventilation rise together -----------------
        # Scaling them equally makes the response isocapnic, which is what
        # healthy subjects show at moderate workloads at sea level.
        ex = exercise_multiplier_func(t)
        current_VO2 = self.VO2 * ex
        current_VCO2 = self.VCO2 * ex

        # --- hypoxic ventilatory response ------------------------------------
        # This is the addition that makes altitude possible. Ventilation now has
        # two multipliers: the volitional/metabolic one from exercise, and the
        # reflex one from hypoxaemia. Their product is total ventilation.
        hvr = float(self.hypoxic_drive(PaO2))
        drive = ex * hvr
        current_VA = self.VA * drive

        # Capillary recruitment follows the same drive, so diffusing capacity
        # rises with altitude and with exercise.
        DL_eff = float(self.effective_DL(drive))

        # --- 1. alveolar oxygen ----------------------------------------------
        PAO2 = self.alveolar_PO2(PaCO2, PiO2)

        # --- 2. arterial O2: diffusion in, consumption out --------------------
        # Fick's law. At steady state the gradient is VO2 / DL_eff.
        dPaO2_dt = (DL_eff * (PAO2 - PaO2) - current_VO2) / self.Vcap

        # --- 3. arterial CO2: production in, ventilation out ------------------
        # Rearranged alveolar ventilation equation, so the steady state is
        # PaCO2* = K * VCO2 / VA. Because VA now rises with hypoxaemia, PaCO2
        # falls at altitude - the hypocapnia of acute altitude exposure.
        dPaCO2_dt = (self.K * current_VCO2 - current_VA * PaCO2) / self.Vcap

        return [dPaO2_dt, dPaCO2_dt]

    def simulate(self, t_span, t_eval, y0, exercise_multiplier_func, PiO2_func=None):
        """
        Integrate the pulmonary ODE system for a single virtual patient.

        `max_step` is capped at 10 minutes so the adaptive solver cannot step
        over the 30-minute exercise window, and so an altitude profile is sampled
        finely enough that the ascent is not jumped.
        """
        return solve_ivp(
            fun=self._respiratory_odes,
            t_span=t_span,
            y0=y0,
            t_eval=t_eval,
            args=(exercise_multiplier_func, PiO2_func),
            method='RK45',
            max_step=10.0,
        )

    def resting_steady_state(self, PiO2=None, tol=1e-6, max_iter=200):
        """
        Resting steady state (PaO2, PaCO2) at a given inspired oxygen tension.

        The two gases are coupled through both the alveolar gas equation and the
        hypoxic drive, so there is no closed form once the ventilatory response
        is active. This solves the fixed point by damped iteration, which
        converges reliably across the altitude range used here.

        Used to start each virtual patient at its own steady state, so a record
        does not open with a settling transient the surrogate would learn as a
        feature of the data.
        """
        PiO2 = self.PiO2 if PiO2 is None else PiO2

        PaO2 = 90.0
        PaCO2 = 40.0
        for _ in range(max_iter):
            drive = float(self.hypoxic_drive(PaO2))
            va = self.VA * drive
            dl = float(self.effective_DL(drive))
            new_PaCO2 = self.K * self.VCO2 / va
            new_PaO2 = float(self.alveolar_PO2(new_PaCO2, PiO2)) - self.VO2 / dl
            new_PaO2 = max(new_PaO2, 1.0)

            # Damping. Undamped iteration oscillates, because raising ventilation
            # lowers CO2, which raises alveolar oxygen, which switches the
            # hypoxic drive back off.
            step = 0.35
            PaO2_next = PaO2 + step * (new_PaO2 - PaO2)
            PaCO2_next = PaCO2 + step * (new_PaCO2 - PaCO2)

            if abs(PaO2_next - PaO2) < tol and abs(PaCO2_next - PaCO2) < tol:
                PaO2, PaCO2 = PaO2_next, PaCO2_next
                break
            PaO2, PaCO2 = PaO2_next, PaCO2_next

        return PaO2, PaCO2

    # ------------------------------------------------------------------
    # Cohort generation (WBS 3.4)
    # ------------------------------------------------------------------

    def generate_synthetic_cohort(self, num_patients=1000, t_max=1440, n_samples=1440,
                                  exercise_start=600.0, exercise_end=630.0,
                                  exercise_factor=2.0,
                                  altitude_profile=True,
                                  ascent_start=120.0, ascent_end=480.0,
                                  descent_start=1080.0, descent_end=1260.0,
                                  target_altitude_range=(2500.0, 5500.0),
                                  residual_altitude=1500.0):
        """
        Generate a synthetic cohort under a high-altitude exposure protocol.

        The protocol is an ascent-hold-descent profile: each patient starts at sea
        level, ascends to their own target altitude, holds there, and then
        descends part way. An exercise bout is applied during the hold, because
        exercise at altitude is the condition of interest rather than exercise at
        sea level.

        This profile is what gives both gas tensions real dynamics. Under the
        previous fixed-ventilation protocol, arterial CO2 was constant in every
        record and could not be learned at all.

        Parameters
        ----------
        altitude_profile : bool
            If False, the cohort is generated at a constant sea-level inspired
            oxygen tension, reproducing the r1 behaviour.
        ascent_start, ascent_end : float
            Minutes over which the ascent occurs.
        descent_start, descent_end : float
            Minutes over which the partial descent occurs.
        target_altitude_range : (float, float)
            Range of per-patient target altitudes (m), drawn uniformly. The upper
            bound is kept at 5,500 m because the standard atmosphere formula is a
            troposphere model.
        residual_altitude : float
            Altitude (m) held after descent.

        Returns
        -------
        pandas.DataFrame
            Long-format cohort, one row per patient per sample.
        """
        all_data = []

        t_eval = np.linspace(0, t_max, n_samples)
        t_span = (0.0, t_max)

        def exercise_disturbance(t):
            """Metabolic and ventilatory multiplier from exercise."""
            return exercise_factor if exercise_start <= t <= exercise_end else 1.0

        for patient_id in range(num_patients):
            # --- per-patient physiological variation ------------------------
            VA_var = np.random.normal(self.VA, self.VA * 0.10)
            DL_var = np.random.normal(self.DL, self.DL * 0.10)

            # Hypoxic ventilatory response varies several fold between people and
            # is one of the better predictors of altitude tolerance, so it gets a
            # wider draw than the mechanical parameters.
            hvr_var = np.random.normal(self.hvr_gain, self.hvr_gain * 0.25)

            VA_var = float(np.clip(VA_var, 0.6 * self.VA, 1.4 * self.VA))
            DL_var = float(np.clip(DL_var, 0.6 * self.DL, 1.4 * self.DL))
            hvr_var = float(np.clip(hvr_var, 0.5, 3.5))

            # --- per-patient altitude profile --------------------------------
            if altitude_profile:
                target = float(np.random.uniform(*target_altitude_range))

                def altitude_at(t, _target=target):
                    """Altitude (m) at time t: sea level, ascent, hold, descent."""
                    if t < ascent_start:
                        return 0.0
                    if t < ascent_end:
                        frac = (t - ascent_start) / (ascent_end - ascent_start)
                        return _target * frac
                    if t < descent_start:
                        return _target
                    if t < descent_end:
                        frac = (t - descent_start) / (descent_end - descent_start)
                        return _target + (residual_altitude - _target) * frac
                    return residual_altitude

                def PiO2_at(t, _alt=altitude_at):
                    return float(inspired_PO2(_alt(t)))
            else:
                target = 0.0
                altitude_at = lambda t: 0.0                      # noqa: E731
                PiO2_at = lambda t: self.PiO2                    # noqa: E731

            temp = LungsODE(PiO2=self.PiO2, VA=VA_var, DL=DL_var,
                            VO2=self.VO2, VCO2=self.VCO2, RQ=self.RQ,
                            Vcap=self.Vcap, hvr_gain=hvr_var,
                            hvr_threshold=self.hvr_threshold,
                            hvr_max=self.hvr_max,
                            recruit_gain=self.recruit_gain,
                            P50=self.P50, hill_n=self.hill_n)

            # --- initial state: this patient's sea-level steady state ---------
            PaO2_0, PaCO2_0 = temp.resting_steady_state(PiO2_at(0.0))
            y0 = [PaO2_0, PaCO2_0]

            sol = temp.simulate(t_span, t_eval, y0, exercise_disturbance, PiO2_at)

            # --- derived output columns ---------------------------------------
            PaO2_arr = sol.y[0]
            PaCO2_arr = sol.y[1]
            alt_arr = np.array([altitude_at(t) for t in sol.t])
            PiO2_arr = inspired_PO2(alt_arr)
            ex_arr = np.array([exercise_disturbance(t) for t in sol.t])
            hvr_arr = temp.hypoxic_drive(PaO2_arr)
            drive_arr = ex_arr * hvr_arr
            dl_arr = temp.effective_DL(drive_arr)

            df = pd.DataFrame({
                'Patient_ID': patient_id,
                'Time_min': sol.t,
                'Arterial_O2_mmHg': PaO2_arr,
                'Arterial_CO2_mmHg': PaCO2_arr,
                'SaO2_percent': temp.oxygen_saturation(PaO2_arr),
                'Alveolar_O2_mmHg': temp.alveolar_PO2(PaCO2_arr, PiO2_arr),
                'Altitude_m': alt_arr,
                'Inspired_O2_mmHg': PiO2_arr,
                'Alveolar_Ventilation_L_min': VA_var * drive_arr,
                'Diffusing_Capacity_mL_min_mmHg': dl_arr,
                'HVR_Gain': hvr_var,
            })
            all_data.append(df)

        return pd.concat(all_data, ignore_index=True)


